def open_shared_image(path: Path):
    """Open a frame arklay has just written. On Windows another process (the virus scanner) can hold a new
    file for a moment, and the open is refused meanwhile: try again for up to two seconds."""
    from PIL import Image

    for _ in range(100):
        try:
            return Image.open(path)
        except PermissionError:
            time.sleep(0.02)
    return Image.open(path)


def frame_error(ref_png: Path, ark_bmp: Path, boxes_variants) -> list[float] | None:
    """Mean error of one tick: the original's 640x480 frame cropped to the game area and boxed down to 320x240, against arklay's.

    One error per entry of `boxes_variants`, each a list of rectangles blanked on both sides first (`[]` for the plain error).
    None when the reference has no frame for this tick. Both the streaming and the post-hoc comparisons use this."""
    from PIL import Image, ImageChops, ImageDraw, ImageStat

    if not ref_png.exists():
        return None
    ref0 = Image.open(ref_png).convert("RGB").crop((3, 29, 643, 509)).resize((320, 240), Image.BOX)
    ark0 = open_shared_image(ark_bmp).convert("RGB")
    result = []
    for boxes in boxes_variants:
        ref, ark = ref0, ark0
        if boxes:
            ref, ark = ref0.copy(), ark0.copy()
            for image in (ref, ark):
                draw = ImageDraw.Draw(image)
                for x0, y0, x1, y1 in boxes:
                    draw.rectangle((x0, y0, x1 - 1, y1 - 1), fill=(0, 0, 0))
        result.append(sum(ImageStat.Stat(ImageChops.difference(ref, ark)).mean) / 3)
    return result


def frame_errors(ref_dir: Path, ark_dir: Path, first: int, last: int, offset: int, variants) -> list[list[tuple[float, int]]]:
    """Per variant of `frame_error`, the (error, tick) of each tick in first..last that both sides have a frame for."""
    errors = [[] for _ in variants]
    for tick in range(first, last + 1):
        ark_bmp = ark_dir / f"f{tick - offset:05d}.bmp"
        if not ark_bmp.exists():
            continue
        values = frame_error(ref_dir / f"t{tick:06d}.png", ark_bmp, variants)
        if values is not None:
            for out, value in zip(errors, values):
                out.append((value, tick))
    return errors


def judge_windows(windows, errors) -> tuple[list[str], list[str]]:
    """`frame_windows`: each `[first, last, max_mean]` judged on the frames of
    its own ticks. Returns the text for each window and the problems."""
    texts, problems = [], []
    for first, last, limit in windows:
        inside = [e for e, tick in errors if first <= tick <= last]
        if not inside:
            problems.append(f"no frames in the window {first}-{last}")
            continue
        mean = sum(inside) / len(inside)
        texts.append(f"{first}-{last} {mean:.2f}")
        if mean > limit:
            problems.append(f"frame mean {mean:.2f} in {first}-{last} is over {limit}")
    return texts, problems


def comparison_start(run: dict) -> tuple[int, str | None]:
    """The reference tick the comparison starts at (`compare_from`, else `offset`), and why it can't be used, if it can't.

    `compare_from` must lie in the run: at or past `offset` (before it, arklay's index would go negative) and before
    `ticks` (at or past it, nothing would be compared). An `ignore` entry that ends before it is never used, so it is
    refused as stale."""
    offset = run.get("offset", 344)
    start = run.get("compare_from", offset)
    if start < offset:
        return start, f"compare_from {start} is before the run's offset {offset}"
    if start >= run["ticks"]:
        return start, f"compare_from {start} is not before the run's last tick {run['ticks']}"
    stale = [entry for entry in run.get("ignore", []) if entry[-2] < start]
    if stale:
        return start, f"ignore {stale} ends before the comparison starts at tick {start}: drop it"
    return start, None


def self_test() -> int:
    """The window judge on a synthetic list of frame errors, and `compare_from`'s bounds."""
    errors = [(1.0, 10), (3.0, 11), (0.2, 20), (0.4, 21), (9.0, 30)]
    texts, problems = judge_windows([[10, 11, 2.0], [20, 21, 0.25], [40, 50, 1.0]], errors)
    want_texts = ["10-11 2.00", "20-21 0.30"]
    want_problems = ["frame mean 0.30 in 20-21 is over 0.25", "no frames in the window 40-50"]
    if texts != want_texts or problems != want_problems:
        print(f"re2-regress self-test FAILED: {texts} {problems}", file=sys.stderr)
        return 1
    # The ignore list: only ticks whose ignored field differed count, and a backwards range is refused.
    rows = [
        {"ref_t": 5, "differences": [("fgroom", "1", "2")]},
        {"ref_t": 6, "differences": [("fgroom", "1", "2"), ("inv", "a", "b")]},
        {"ref_t": 9, "differences": [("fl", "0", "1")]},
    ]
    divergent, ignored = drop_ignored(rows, ignore_pairs([[0, 100, "fgroom"], [9, "inv"]]))
    if ignored != 2 or divergent != [(6, [("inv", "a", "b")]), (9, [("fl", "0", "1")])]:
        print(f"re2-regress self-test FAILED: ignore gave {divergent} {ignored}", file=sys.stderr)
        return 1
    try:
        ignore_pairs([[20, 10, "fgroom"]])
        print("re2-regress self-test FAILED: a backwards ignore range was accepted", file=sys.stderr)
        return 1
    except SystemExit:
        pass
    starts = [comparison_start({"ticks": 3000, **extra}) for extra in ({}, {"compare_from": 1818})]
    bad = [comparison_start({"ticks": 3000, "compare_from": at})[1] for at in (343, 3000, 4000)]
    bad.append(comparison_start({"ticks": 3000, "compare_from": 1818, "ignore": [[400, 1817, "rng"]]})[1])
    kept = comparison_start({"ticks": 3000, "compare_from": 1818, "ignore": [[400, 1818, "rng"], [1900, "inv"]]})
    if starts != [(344, None), (1818, None)] or None in bad or kept != (1818, None):
        print(f"re2-regress self-test FAILED: compare_from {starts} {bad}", file=sys.stderr)
        return 1
    problem = (self_test_fields() or self_test_gallery_hold() or self_test_pace() or self_test_pictures()
               or self_test_save_images() or self_test_title_voice())
    if problem:
        print(f"re2-regress self-test FAILED: {problem}", file=sys.stderr)
        return 1
    print("re2-regress self-test ok")
    return 0


