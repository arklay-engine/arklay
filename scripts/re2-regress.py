def run_inputs(run: dict, out: Path, tag: str) -> tuple[Path | None, Path, str | None]:
    """A run's setup chunk and its input as arklay takes them, written under `out` as `tag`'s where they are made;
    and the name of one that is missing."""
    if run.get("ui", "game") != "game":
        setup = None
    elif run.get("setup_script"):
        setup = INPUTS / run["setup_script"]
    else:
        setup = out / f"{tag}.setup.lua"
        setup.write_text(setup_lua(run["setup"]))
    if run.get("input_shift"):
        input_path = out / f"{tag}.input.txt"
        shift_input(INPUTS / run["input"], input_path, run["input_shift"], run.get("input_drop_early", False))
    else:
        input_path = INPUTS / run["input"]
    for needed in (setup, input_path):
        if needed is not None and not needed.exists():
            return setup, input_path, needed.name
    return setup, input_path, None


def seed_saves(run: dict, ctx: dict, saves_dir: Path) -> str | None:
    """Fill `saves_dir` for a run with `saves_from`: arklay's own saves of the run it names, since the reference's are
    the original's `.BIOHAZARD2` files, which arklay doesn't read. arklay plays that run first, with no trace
    compared and no frames, and each save it keeps takes the name and the time of the reference's file of its count,
    so the list shows the rows the original's record shows. Returns why it couldn't."""
    name, out = run["name"], ctx["out"]
    source = ctx["manifest"].get(run["saves_from"])
    if source is None or source.get("ui", "game") != "game" or not source.get("saves"):
        return f"saves_from: {run['saves_from']} isn't a game run that keeps its saves"
    ref_saves = sorted((ctx["refs"] / source["ref"] / "saves").glob("*.BIOHAZARD2"))
    if not ref_saves:
        return f"saves_from: no saves in the reference {source['ref']} (see: re2-regress.py record {source['name']})"
    tag = f"{name}.seed"
    setup, input_path, missing = run_inputs(source, out, tag)
    if missing:
        return f"saves_from: {missing} is missing"
    driver = out / f"{tag}.driver.lua"
    driver.write_text(driver_lua(source, ctx, "game", source["ticks"] - source.get("offset", 344),
                                 out / f"{tag}.ark.trace", input_path, setup, saves_dir, None, None))
    if STOP.is_set():
        raise Interrupted()
    with open(out / f"{tag}.log", "w") as log:
        proc = subprocess.Popen([str(ctx["arklay"]), "script", "--headless", str(driver)], cwd=ROOT, stdout=log,
                                stderr=subprocess.STDOUT, text=True)
        with LIVE_LOCK:
            LIVE.add(proc)
        try:
            wait_for(proc)
        except BaseException:
            proc.kill()
            proc.wait()
            raise
        finally:
            with LIVE_LOCK:
                LIVE.discard(proc)
    log_text = (out / f"{tag}.log").read_text(errors="replace")
    if STALE_PACK in log_text:
        return STALE_PACK_TEXT
    if proc.returncode:
        return f"saves_from: arklay exited {proc.returncode} playing {source['name']} ({tag}.log)"
    final = json_lines(log_text, "save-final")
    made = {row["count"]: row["name"] for row in final[-1][1] if "count" in row} if final else {}
    by_count = {save_count(path): path for path in ref_saves}
    if sorted(made) != sorted(by_count):
        return f"saves_from: arklay kept saves {sorted(made)} playing {source['name']}, the reference {sorted(by_count)}"
    # Each save takes the name and the time of the reference's of its count, so the list shows the original's rows.
    for count, ref_save in by_count.items():
        named = saves_dir / (ref_save.stem + ".dat")
        (saves_dir / made[count]).rename(named)
        times = ref_save.stat()
        os.utime(named, ns=(times.st_atime_ns, times.st_mtime_ns))
    if not ctx["keep"]:
        for path in out.glob(f"{tag}.*"):
            path.unlink()
    return None


def run_one(run: dict, ctx: dict) -> dict:
    name = run["name"]
    out: Path = ctx["out"]
    ref_dir: Path = ctx["refs"] / run["ref"]
    result = {"name": name, "problems": [], "notes": [], "text": ""}
    ref_trace = ref_dir / "ref.trace"
    if not ref_trace.exists():
        result["text"] = f"no reference {run['ref']} (see: re2-regress.py record {name})"
        result["problems"].append("missing reference")
        result["missing"] = True
        return result

    offset = run.get("offset", 344)
    ticks = run["ticks"] - offset
    compare_from, why = comparison_start(run)
    if why:
        result["text"] = why
        result["problems"].append(why)
        return result
    screen = run.get("ui", "game")
    setup, input_path, missing = run_inputs(run, out, name)
    if missing:
        result["problems"].append(f"{missing} is missing")
        result["text"] = "setup or input missing"
        return result

    want_frames = bool(run.get("frames")) and (ref_dir / "frames").is_dir()
    ark_trace = out / f"{name}.ark.trace"
    frames_dir = ctx["capture_root"] / f"{name}.frames"
    stream = want_frames and not ctx["keep"]  # compare frames as arklay writes them, and delete each
    # A save folder of its own, empty, as the original's record starts with: the save screen lists
    # it, and a run never writes the user's.
    saves_dir = out / f"{name}.saves"
    if saves_dir.exists():
        shutil.rmtree(saves_dir)
    saves_dir.mkdir(parents=True)
    voice = None
    # A title run's lines are the game's the title starts (a `--boot` record has sound unless the run says not).
    if screen in ("game", "title") and run.get("sound", True) and run.get("voice_from_ref"):
        voice = voice_ticks(ref_trace)
    driver = out / f"{name}.driver.lua"
    films = film_pads(ref_dir) if screen == "game" and run.get("films_from_ref") else None
    driver.write_text(driver_lua(run, ctx, screen, ticks, ark_trace, input_path, setup, saves_dir,
                                 frames_dir if want_frames else None, voice, films))
    command = [str(ctx["arklay"]), "script", "--headless", str(driver)]
    try:
        if run.get("saves_from"):
            why = seed_saves(run, ctx, saves_dir)
            if why:
                result["text"] = why
                result["problems"].append("stale pack" if why == STALE_PACK_TEXT else why)
                return result
        return finish_run(run, ctx, result, command, frames_dir, want_frames, stream, ticks, offset, compare_from,
                          ref_dir, ref_trace, ark_trace, saves_dir)
    finally:
        if not ctx["keep"]:
            shutil.rmtree(saves_dir, ignore_errors=True)
        if stream:
            keep_failed_frames(result, frames_dir, out / f"{name}.frames")


def keep_failed_frames(result: dict, frames_dir: Path, dest: Path) -> None:
    """After a streamed run: a failed run's frames that are left (the newest and the worst) go to out/<name>.frames
    for debugging; otherwise the capture folder is removed."""
    if result["problems"] and not STOP.is_set() and frames_dir.is_dir() and any(frames_dir.iterdir()):
        if frames_dir != dest:
            shutil.rmtree(dest, ignore_errors=True)
            shutil.move(frames_dir, dest)
        count = sum(1 for _ in dest.glob("f*.bmp"))
        result["notes"].append(f"kept {count} frames, the newest and the worst, in {dest} (--keep keeps every frame)")
    else:
        shutil.rmtree(frames_dir, ignore_errors=True)


def wait_for(proc) -> None:
    """Wait for arklay, stopping early on Ctrl-C, SIGTERM or SIGHUP."""
    while True:
        try:
            proc.wait(timeout=0.1)
            return
        except subprocess.TimeoutExpired:
            if STOP.is_set():
                raise Interrupted() from None


def finish_run(run, ctx, result, command, frames_dir, want_frames, stream, ticks, offset, compare_from, ref_dir,
               ref_trace, ark_trace, saves_dir) -> dict:
    """The rest of `run_one`: play arklay (capturing frames), then compare the trace and the frames."""
    name = run["name"]
    out: Path = ctx["out"]
    first, last = run.get("frames", (0, -1))
    boxes = [tuple(box) for box in run.get("boxes", [])]
    variants = [[], boxes] if boxes else [[]]
    streamed = None
    if want_frames:
        prepare_capture(frames_dir)
    # The output goes to files, not pipes, so that polling for frames can't leave arklay blocked on a full pipe.
    # arklay writes UTF-8 (a pack's path in a warning, say), whatever the locale's encoding.
    output = {"mode": "w+", "encoding": "utf-8", "errors": "replace"}
    with tempfile.TemporaryFile(**output) as stdout, tempfile.TemporaryFile(**output) as stderr:
        if STOP.is_set():
            raise Interrupted()
        proc = subprocess.Popen(command, cwd=ROOT, stdout=stdout, stderr=stderr, text=True)
        with LIVE_LOCK:
            LIVE.add(proc)
        try:
            if stream:
                streamed = stream_frames(proc, ref_dir / "frames", frames_dir, first, last, offset, variants, ticks,
                                         ctx["comparers"], ctx["workers"])
            else:
                wait_for(proc)
        except BaseException:
            proc.kill()
            proc.wait()
            raise
        finally:
            with LIVE_LOCK:
                LIVE.discard(proc)
        stdout.seek(0)
        stderr.seek(0)
        out_text, err_text = stdout.read(), stderr.read()
    (out / f"{name}.log").write_text(out_text + err_text, encoding="utf-8")
    # Checked first, as a stale pack's other scripts can be why arklay failed.
    if STALE_PACK in err_text:
        result["text"] = STALE_PACK_TEXT
        result["problems"].append("stale pack")
        return result
    if proc.returncode:
        result["text"] = f"arklay exited {proc.returncode}: {err_text.strip()[-200:]}"
        result["problems"].append("arklay failed")
        return result

    ref_f, ark_f = out / f"{name}.ref.f", out / f"{name}.ark.f"
    if run.get("keep_sound_3"):
        shutil.copy(ref_trace, ref_f)
        shutil.copy(ark_trace, ark_f)
    else:
        drop_sound_3(ref_trace, ref_f)
        drop_sound_3(ark_trace, ark_f)
    # `compare_from`: a reference tick past `offset` the comparison starts at, for a run whose
    # start isn't comparable yet (a scene not ported) but whose rest is.
    cmp = compare_traces(ref_f, ark_f, compare_from, run["fields"], run.get("ignore", []), compare_from - offset)
    ref_f.unlink()
    ark_f.unlink()
    text = trace_text(cmp)
    if compare_from != offset:
        text += f" from tick {compare_from}"
    if cmp["ticks"] == 0:
        result["problems"].append("no ticks compared")
    elif cmp["ticks"] < ticks - (compare_from - offset):
        # compare_pair stops at the shorter trace, so a short one would otherwise pass.
        wanted = ticks - (compare_from - offset)
        result["problems"].append(f"only {cmp['ticks']} of {wanted} ticks compared (a trace ended early)")
    why = judge_trace(run, cmp)
    if why:
        result["problems"].append(why)
        result["notes"] += cmp["detail"]

    if run.get("saves") and run.get("ui", "game") == "game":
        start = []
        if run.get("saves_from"):
            source = ctx["manifest"][run["saves_from"]]
            start = [count for path in newest_first(reference_saves(ctx["refs"] / source["ref"]))
                     if (count := save_count(path)) is not None]
        saves_text, problems = judge_save_images(ref_dir, out_text, start)
        text += f"; {saves_text}"
        result["problems"].extend(problems)

    if run.get("frames"):
        if not want_frames:
            text += "; frames: no reference frames"
            limits = [key for key in ("frame_max_mean", "frame_windows") if run.get(key) is not None]
            if limits:
                # A limit nothing is held to would let the run pass on its trace alone.
                result["problems"].append(f"the reference has no frames for {' and '.join(limits)}: record it again")
        else:
            if streamed is None:
                streamed = {"errors": frame_errors(ref_dir / "frames", frames_dir, first, last, offset, variants), "outside": []}
            if streamed["outside"]:
                result["problems"].append(f"{len(streamed['outside'])} frames this run didn't write (from f{min(streamed['outside']):05d})")
            streamed = streamed["errors"]
            per_tick = streamed[0]  # (error, tick) for every compared tick of first..last, plain; what frame_windows is judged on
            plain = frame_summary(per_tick)
            if plain["count"] == 0:
                result["problems"].append("no frames to compare")
            worst = " ".join(f"t{t}:{e:.2f}" for e, t in plain["worst"])
            text += f"; frames {plain['count']} mean {plain['mean']:.2f} worst {worst}"
            if boxes:
                boxed = frame_summary(streamed[1])
                text += f" (box blanked {boxed['mean']:.2f})"
            limit = run.get("frame_max_mean")
            if limit is not None and plain["mean"] > limit:
                result["problems"].append(f"frame mean {plain['mean']:.2f} is over {limit}")
            if run.get("frame_windows"):
                texts, problems = judge_windows(run["frame_windows"], per_tick)
                text += "; windows " + ", ".join(texts)
                result["problems"].extend(problems)
    if not ctx["keep"]:
        ark_trace.unlink(missing_ok=True)
    result["text"] = text
    return result


