def setup_lua(setup: dict) -> str:
    """The Lua of a setup table: what the original's state is at the run's tick 0."""
    lines = ["-- generated by scripts/re2-regress.py from oracle/re2-regress.toml", "local api = ..."]
    x, y, z = setup["pos"]
    lines.append(f"api:set_player_pos({x}, {y}, {z})")
    lines.append(f"api:set_player_angle({setup.get('angle', 0)})")
    lines.append(f"api:set_health({setup.get('health', 200)})")
    if "rnd" in setup:
        lines.append(f"api:set_re2_rnd({setup['rnd']})")
    if "sce_rnd" in setup:
        lines.append(f"api:set_re2_sce_rnd({setup['sce_rnd']})")
    if "camera" in setup:
        lines.append(f"api:set_room_camera({setup['camera']})")
    for bank, index in setup.get("flags", []):
        lines.append(f"api:set_re2_flag({bank}, {index})")
    return "\n".join(lines) + "\n"


def choice_args(run: dict) -> list[str]:
    """The new game's choice a run asks for (`difficulty = "hard"`, `arrange = true`), for both engines: the
    original's title route and arklay's start take the same options. It is not in the setup script, which runs after
    the room's first load."""
    choice = []
    if run.get("difficulty", "normal") != "normal":
        choice += ["--difficulty", run["difficulty"]]
    if run.get("arrange"):
        choice.append("--arrange")
    return choice


def shift_input(source: Path, dest: Path, shift: int, drop_early: bool = False) -> None:
    """The input with every tick moved `shift` ticks earlier, for a run that starts at the original's tick `shift`.

    With `drop_early`, what the input does before `shift` is left out (the pad is neutral at `shift`, as the manifest
    says by using it) and the run starts with a neutral line."""
    out = []
    for line in source.read_text().splitlines():
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        tick, _, rest = text.partition(" ")
        moved = int(tick) - shift
        if moved < 0 and drop_early:
            continue
        if moved < 0:
            raise SystemExit(f"{source}: tick {tick} is before the shift of {shift}")
        out.append(f"{moved} {rest}".rstrip())
    if drop_early and not (out and out[0].split()[0] == "0"):
        out.insert(0, "0")
    dest.write_text("\n".join(out) + "\n")


# ---------------------------------------------------------------- traces


def drop_sound_3(source: Path, dest: Path) -> None:
    """Copy a trace without the `3:` entries of `snd`: arklay's --room start plays room sounds the original's warp doesn't."""

    def clean(match):
        kept = [x for x in match.group(1).split("/") if x != "-" and not x.startswith("3:")]
        return " snd=" + ("/".join(kept) or "-")

    with open(source) as src, open(dest, "w") as out:
        for line in src:
            out.write(re.sub(r" snd=(\S+)", clean, line))


def voice_ticks(trace: Path) -> list[int]:
    """How long each voice line held `fg_status`'s voice bit (flag 1:26, `0x20`) in the recording, in order.

    With `--sound` the original ends a line by DirectSound's clock, so a line's length in ticks follows the
    recording's pace (`docs/internals/deviations/re2.md`, "Voice lines"); a run with `voice_from_ref` hands arklay these."""
    held = []
    start = None
    with open(trace) as lines:
        for line in lines:
            tick = re.match(r"t=(\d+) ", line)
            status = re.search(r" fgstat=([0-9a-f]+)", line)
            if not tick or not status:
                continue
            on = int(status.group(1), 16) & 0x20 != 0
            if on and start is None:
                start = int(tick.group(1))
            elif not on and start is not None:
                held.append(int(tick.group(1)) - start)
                start = None
    return held


# The flag-bank fields a reference recorded before they existed lacks (`fgitem` is newer than the rest).
# A run that names one of them against such a reference would compare `absent` with arklay's value on
# every tick; the runner says why instead. Only these keys are checked: others (`em`, `hk`) are
# legitimately absent from some ticks.
BANK_FIELDS = ("fgitem", "fgroom", "fgscn", "fgstat")


def missing_bank_fields(ref: list, offset: int, fields: str) -> list[str]:
    """The bank fields `fields` names that the reference carries on no compared tick."""
    named = [name for name in fields.split(",") if name in BANK_FIELDS] if fields else []
    present = set()
    for tick in ref[offset:]:
        present.update(key for key, _ in oracle.tick_fields(tick))
    return [name for name in named if name not in present]


def ignore_pairs(ignore) -> set:
    """The (reference tick, field) pairs a run's `ignore` list names. An entry is [tick, field], or
    [first, last, field] for a run of ticks; a range that ends before it starts is a manifest error."""
    pairs = set()
    for entry in ignore:
        if len(entry) not in (2, 3):
            raise SystemExit(f"re2-regress: ignore entry {entry} is not [tick, field] or [first, last, field]")
        first, last = entry[0], entry[-2]
        if last < first:
            raise SystemExit(f"re2-regress: ignore entry {entry} ends before it starts")
        pairs.update((tick, entry[-1]) for tick in range(first, last + 1))
    return pairs


def drop_ignored(rows, skip: set) -> tuple[list, int]:
    """The differing ticks left once the ignored pairs are dropped, and how many ticks had an ignored
    field that actually differed (a tick in an ignored range that matched is not counted)."""
    divergent = []
    ignored = 0
    for row in rows:
        kept = [d for d in row["differences"] if (row["ref_t"], d[0]) not in skip]
        if len(kept) < len(row["differences"]):
            ignored += 1
        if kept:
            divergent.append((row["ref_t"], kept))
    return divergent, ignored


def compare_traces(ref_path: Path, ark_path: Path, offset: int, fields: str, ignore=(), ark_offset: int = 0) -> dict:
    """Compare from reference tick `offset` (arklay's `ark_offset`), leaving out the (reference tick, field) pairs the manifest says differ for a known reason."""
    ref = oracle.parse_trace(str(ref_path))
    ark = oracle.parse_trace(str(ark_path))
    missing = missing_bank_fields(ref, offset, fields)
    if missing:
        return {
            "ticks": 0, "matched": 0, "tick": 0, "fields": missing, "ignored": 0,
            "detail": [f"the reference has no {name} (recorded before it existed): record it again or drop the field" for name in missing],
        }
    result = oracle.compare_pair(ref, ark, offset, ark_offset, 10**9, 0, fields.split(",") if fields else None)
    divergent, ignored = drop_ignored(result["first_divergences"], ignore_pairs(ignore))
    first = divergent[0] if divergent else None
    return {
        "ticks": result["length"],
        "matched": result["length"] - len(divergent),
        "tick": first[0] if first else None,
        "fields": [d[0] for d in first[1]] if first else [],
        "detail": [f"{k}: ref={a} ark={b}" for k, a, b in first[1][:3]] if first else [],
        "ignored": ignored,
    }


def trace_text(cmp: dict) -> str:
    if cmp["tick"] is None:
        extra = f" (not counting {cmp['ignored']} known differences)" if cmp["ignored"] else ""
        return f"trace MATCH {cmp['ticks']} ticks{extra}"
    shown = ",".join(cmp["fields"][:4]) + ("..." if len(cmp["fields"]) > 4 else "")
    return f"trace {cmp['matched']}/{cmp['ticks']} ticks, first differs at tick {cmp['tick']} ({shown})"


def judge_trace(run: dict, cmp: dict) -> str | None:
    """None when the trace is what the manifest expects, else why not."""
    expect = run.get("expect", "match")
    if expect == "match":
        return None if cmp["tick"] is None else "expected a match"
    if cmp["tick"] is None:
        return f"expected a first divergence at tick {expect['tick']}, got a match (update the manifest)"
    if cmp["tick"] != expect["tick"] or set(cmp["fields"]) != set(expect["fields"]):
        return (
            f"expected first divergence at tick {expect['tick']} in {','.join(expect['fields'])}, "
            f"got tick {cmp['tick']} in {','.join(cmp['fields'])}"
        )
    return None


