#!/usr/bin/env python3
"""Check arklay's RE 2 against the stored recordings of the original.

Every run in oracle/re2-regress.toml names a reference (a folder in the refs dir
holding ref.trace and, for some, frames/), the arklay command that plays the same
input, the fields to compare, and the expected result: a match, or a known first
divergence. The original is deterministic (oracle/re2.md), so a reference is
recorded once and reused.

  scripts/re2-regress.py --out DIR [NAME...]          run the manifest (or the named runs)
  scripts/re2-regress.py --out DIR --list             list the runs and whether their reference exists
  scripts/re2-regress.py --out DIR record NAME...     record a missing reference (needs wine)
  scripts/re2-regress.py --self-test                  check the frame windows' judge (check.sh runs it)

Exits non-zero when any run gives an unexpected result. See "The regression
runner" in oracle/re2.md.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import datetime
import hashlib
import importlib.util
import os
import re
import shlex
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "oracle" / "re2-regress.toml"
INPUTS = ROOT / "oracle" / "inputs-re2"
DEFAULT_REFS = "~/.local/share/arklay/re2-refs"
DEFAULT_ARKLAY = ROOT / "target" / "test-release" / ("arklay.exe" if sys.platform == "win32" else "arklay")


def load_oracle():
    spec = importlib.util.spec_from_file_location("oracle", ROOT / "scripts" / "oracle.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["oracle"] = module
    spec.loader.exec_module(module)
    return module


oracle = load_oracle()


# ---------------------------------------------------------------- manifest


def load_manifest(path: Path) -> tuple[dict, list[dict]]:
    with open(path, "rb") as handle:
        data = tomllib.load(handle)
    defaults = data.get("defaults", {})
    fieldsets = data.get("fields", {})
    entries = list(data.get("run", []))
    # More runs, one file each or one per family, in `<manifest stem>.d/`: a new
    # run there doesn't touch the lines every other new run appends to.
    for extra in sorted((path.parent / f"{path.stem}.d").glob("*.toml")):
        with open(extra, "rb") as handle:
            more = tomllib.load(handle)
        unknown = set(more) - {"run"}
        if unknown:
            raise SystemExit(f"re2-regress: {extra} may only hold [[run]] tables, not {sorted(unknown)}")
        entries.extend(more.get("run", []))
    runs = []
    for entry in entries:
        run = {**defaults, **entry}
        run.setdefault("ref", run["name"])
        fields = run.get("fields", "")
        run["fields"] = fieldsets.get(fields, fields)
        runs.append(run)
    names = [run["name"] for run in runs]
    if len(set(names)) != len(names):
        raise SystemExit("re2-regress: duplicate run names in the manifest")
    return data, runs


def refs_dir(args) -> Path:
    text = args.refs or os.environ.get("ARKLAY_RE2_REFS") or DEFAULT_REFS
    return Path(text).expanduser()


# ---------------------------------------------------------------- inputs


def setup_lua(setup: dict) -> str:
    """The Lua of a setup table: what the original's state is at the run's tick 0."""
    lines = ["-- generated by scripts/re2-regress.py from oracle/re2-regress.toml", "local api = ..."]
    x, y, z = setup["pos"]
    lines.append(f"api:set_player_pos({x}, {y}, {z})")
    lines.append(f"api:set_player_angle({setup.get('angle', 0)})")
    lines.append(f"api:set_health({setup.get('health', 200)})")
    if "rnd" in setup:
        lines.append(f"api:set_re2_rnd({setup['rnd']})")
    if "sce_rnd" in setup:
        lines.append(f"api:set_re2_sce_rnd({setup['sce_rnd']})")
    if "camera" in setup:
        lines.append(f"api:set_room_camera({setup['camera']})")
    for bank, index in setup.get("flags", []):
        lines.append(f"api:set_re2_flag({bank}, {index})")
    return "\n".join(lines) + "\n"


def choice_args(run: dict) -> list[str]:
    """The new game's choice a run asks for (`difficulty = "hard"`, `arrange = true`), for both engines: the
    original's title route and arklay's start take the same options. It is not in the setup script, which runs after
    the room's first load."""
    choice = []
    if run.get("difficulty", "normal") != "normal":
        choice += ["--difficulty", run["difficulty"]]
    if run.get("arrange"):
        choice.append("--arrange")
    return choice


def shift_input(source: Path, dest: Path, shift: int, drop_early: bool = False) -> None:
    """The input with every tick moved `shift` ticks earlier, for a run that starts at the original's tick `shift`.

    With `drop_early`, what the input does before `shift` is left out (the pad is neutral at `shift`, as the manifest
    says by using it) and the run starts with a neutral line."""
    out = []
    for line in source.read_text().splitlines():
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        tick, _, rest = text.partition(" ")
        moved = int(tick) - shift
        if moved < 0 and drop_early:
            continue
        if moved < 0:
            raise SystemExit(f"{source}: tick {tick} is before the shift of {shift}")
        out.append(f"{moved} {rest}".rstrip())
    if drop_early and not (out and out[0].split()[0] == "0"):
        out.insert(0, "0")
    dest.write_text("\n".join(out) + "\n")


# ---------------------------------------------------------------- traces


def drop_sound_3(source: Path, dest: Path) -> None:
    """Copy a trace without the `3:` entries of `snd`: arklay's --room start plays room sounds the original's warp doesn't."""

    def clean(match):
        kept = [x for x in match.group(1).split("/") if x != "-" and not x.startswith("3:")]
        return " snd=" + ("/".join(kept) or "-")

    with open(source) as src, open(dest, "w") as out:
        for line in src:
            out.write(re.sub(r" snd=(\S+)", clean, line))


def voice_ticks(trace: Path) -> list[int]:
    """How long each voice line held `fg_status`'s voice bit (flag 1:26, `0x20`) in the recording, in order.

    With `--sound` the original ends a line by DirectSound's clock, so a line's length in ticks follows the
    recording's pace (`docs/internals/deviations/re2.md`, "Voice lines"); a run with `voice_from_ref` hands arklay these."""
    held = []
    start = None
    with open(trace) as lines:
        for line in lines:
            tick = re.match(r"t=(\d+) ", line)
            status = re.search(r" fgstat=([0-9a-f]+)", line)
            if not tick or not status:
                continue
            on = int(status.group(1), 16) & 0x20 != 0
            if on and start is None:
                start = int(tick.group(1))
            elif not on and start is not None:
                held.append(int(tick.group(1)) - start)
                start = None
    return held


# The flag-bank fields a reference recorded before they existed lacks (`fgitem` is newer than the rest).
# A run that names one of them against such a reference would compare `absent` with arklay's value on
# every tick; the runner says why instead. Only these keys are checked: others (`em`, `hk`) are
# legitimately absent from some ticks.
BANK_FIELDS = ("fgitem", "fgroom", "fgscn", "fgstat")


def missing_bank_fields(ref: list, offset: int, fields: str) -> list[str]:
    """The bank fields `fields` names that the reference carries on no compared tick."""
    named = [name for name in fields.split(",") if name in BANK_FIELDS] if fields else []
    present = set()
    for tick in ref[offset:]:
        present.update(key for key, _ in oracle.tick_fields(tick))
    return [name for name in named if name not in present]


def compare_traces(ref_path: Path, ark_path: Path, offset: int, fields: str, ignore=()) -> dict:
    """Compare from `offset`, leaving out the (reference tick, field) pairs the manifest says differ for a known reason."""
    ref = oracle.parse_trace(str(ref_path))
    ark = oracle.parse_trace(str(ark_path))
    missing = missing_bank_fields(ref, offset, fields)
    if missing:
        return {
            "ticks": 0, "matched": 0, "tick": 0, "fields": missing, "ignored": 0,
            "detail": [f"the reference has no {name} (recorded before it existed): record it again or drop the field" for name in missing],
        }
    result = oracle.compare_pair(ref, ark, offset, 0, 10**9, 0, fields.split(",") if fields else None)
    # An entry is [tick, field], or [first, last, field] for a run of ticks.
    skip = {
        (tick, entry[-1])
        for entry in ignore
        for tick in range(entry[0], entry[-2] + 1)
    }
    divergent = []
    for row in result["first_divergences"]:
        kept = [d for d in row["differences"] if (row["ref_t"], d[0]) not in skip]
        if kept:
            divergent.append((row["ref_t"], kept))
    first = divergent[0] if divergent else None
    return {
        "ticks": result["length"],
        "matched": result["length"] - len(divergent),
        "tick": first[0] if first else None,
        "fields": [d[0] for d in first[1]] if first else [],
        "detail": [f"{k}: ref={a} ark={b}" for k, a, b in first[1][:3]] if first else [],
        "ignored": len(skip),
    }


def trace_text(cmp: dict) -> str:
    if cmp["tick"] is None:
        extra = f" (not counting {cmp['ignored']} known differences)" if cmp["ignored"] else ""
        return f"trace MATCH {cmp['ticks']} ticks{extra}"
    shown = ",".join(cmp["fields"][:4]) + ("..." if len(cmp["fields"]) > 4 else "")
    return f"trace {cmp['matched']}/{cmp['ticks']} ticks, first differs at tick {cmp['tick']} ({shown})"


def judge_trace(run: dict, cmp: dict) -> str | None:
    """None when the trace is what the manifest expects, else why not."""
    expect = run.get("expect", "match")
    if expect == "match":
        return None if cmp["tick"] is None else "expected a match"
    if cmp["tick"] is None:
        return f"expected a first divergence at tick {expect['tick']}, got a match (update the manifest)"
    if cmp["tick"] != expect["tick"] or set(cmp["fields"]) != set(expect["fields"]):
        return (
            f"expected first divergence at tick {expect['tick']} in {','.join(expect['fields'])}, "
            f"got tick {cmp['tick']} in {','.join(cmp['fields'])}"
        )
    return None


# ---------------------------------------------------------------- frames


def frame_errors(ref_dir: Path, ark_dir: Path, first: int, last: int, offset: int, boxes) -> list[tuple[float, int]]:
    """Mean error per tick: the original's 640x480 frame cropped to the game area and boxed down to 320x240, against arklay's."""
    from PIL import Image, ImageChops, ImageDraw, ImageStat

    errors = []
    for tick in range(first, last + 1):
        ref_png = ref_dir / f"t{tick:06d}.png"
        ark_bmp = ark_dir / f"f{tick - offset:05d}.bmp"
        if not (ref_png.exists() and ark_bmp.exists()):
            continue
        ref = Image.open(ref_png).convert("RGB").crop((3, 29, 643, 509)).resize((320, 240), Image.BOX)
        ark = Image.open(ark_bmp).convert("RGB")
        for image in (ref, ark):
            draw = ImageDraw.Draw(image)
            for x0, y0, x1, y1 in boxes:
                draw.rectangle((x0, y0, x1 - 1, y1 - 1), fill=(0, 0, 0))
        errors.append((sum(ImageStat.Stat(ImageChops.difference(ref, ark)).mean) / 3, tick))
    return errors


def judge_windows(windows, errors) -> tuple[list[str], list[str]]:
    """`frame_windows`: each `[first, last, max_mean]` judged on the frames of
    its own ticks. Returns the text for each window and the problems."""
    texts, problems = [], []
    for first, last, limit in windows:
        inside = [e for e, tick in errors if first <= tick <= last]
        if not inside:
            problems.append(f"no frames in the window {first}-{last}")
            continue
        mean = sum(inside) / len(inside)
        texts.append(f"{first}-{last} {mean:.2f}")
        if mean > limit:
            problems.append(f"frame mean {mean:.2f} in {first}-{last} is over {limit}")
    return texts, problems


def self_test() -> int:
    """The window judge on a synthetic list of frame errors."""
    errors = [(1.0, 10), (3.0, 11), (0.2, 20), (0.4, 21), (9.0, 30)]
    texts, problems = judge_windows([[10, 11, 2.0], [20, 21, 0.25], [40, 50, 1.0]], errors)
    want_texts = ["10-11 2.00", "20-21 0.30"]
    want_problems = ["frame mean 0.30 in 20-21 is over 0.25", "no frames in the window 40-50"]
    if texts != want_texts or problems != want_problems:
        print(f"re2-regress self-test FAILED: {texts} {problems}", file=sys.stderr)
        return 1
    print("re2-regress self-test ok")
    return 0


def frame_summary(errors) -> dict:
    if not errors:
        return {"count": 0, "mean": 0.0, "worst": []}
    return {
        "count": len(errors),
        "mean": sum(e for e, _ in errors) / len(errors),
        "worst": sorted(errors, reverse=True)[:3],
    }


# ---------------------------------------------------------------- one run


def run_one(run: dict, ctx: dict) -> dict:
    name = run["name"]
    out: Path = ctx["out"]
    ref_dir: Path = ctx["refs"] / run["ref"]
    result = {"name": name, "problems": [], "notes": [], "text": ""}
    ref_trace = ref_dir / "ref.trace"
    if not ref_trace.exists():
        result["text"] = f"no reference {run['ref']} (see: re2-regress.py record {name})"
        result["problems"].append("missing reference")
        result["missing"] = True
        return result

    offset = run.get("offset", 344)
    ticks = run["ticks"] - offset
    screen = run.get("ui", "game")
    if screen != "game":
        setup = None
    elif run.get("setup_script"):
        setup = INPUTS / run["setup_script"]
    else:
        setup = out / f"{name}.setup.lua"
        setup.write_text(setup_lua(run["setup"]))
    if run.get("input_shift"):
        input_path = out / f"{name}.input.txt"
        shift_input(INPUTS / run["input"], input_path, run["input_shift"], run.get("input_drop_early", False))
    else:
        input_path = INPUTS / run["input"]
    for needed in (setup, input_path):
        if needed is not None and not needed.exists():
            result["problems"].append(f"{needed.name} is missing")
            result["text"] = "setup or input missing"
            return result

    want_frames = bool(run.get("frames")) and (ref_dir / "frames").is_dir()
    ark_trace = out / f"{name}.ark.trace"
    frames_dir = out / f"{name}.frames"
    # `room = "new"` starts arklay's new game, as the original's record does, with no `--room`.
    start = [] if run["room"] == "new" else ["--room", str(run["room"]), "--player", str(run.get("player", 0))]
    if screen != "game":
        # A screen before play (`ui = "title"`): arklay boots it, and the reference is a `--boot` record.
        command = [
            str(ctx["arklay"]), str(ctx["pack"]), "--ui", screen,
            "--no-mods", "--ticks", str(ticks), "--trace", str(ark_trace), "--input", str(input_path),
        ]
        if "special" in run:
            # config.ini's SPECIAL, which the record's `--config SPECIAL=N` sets.
            command += ["--title-special", str(run["special"])]
    else:
        command = [
            str(ctx["arklay"]), str(ctx["pack"]), "--ui", "game", *start,
            "--character", str(run.get("character", 0)),
            "--no-mods", "--ticks", str(ticks), "--trace", str(ark_trace),
            "--setup-script", str(setup), "--input", str(input_path), *choice_args(run),
        ]
        if run.get("sound", True):
            command.append("--sound")
            if run.get("voice_from_ref"):
                voice = out / f"{name}.voice.txt"
                voice.write_text("".join(f"{held}\n" for held in voice_ticks(ref_trace)))
                command += ["--voice-ticks", str(voice)]
    if want_frames:
        frames_dir.mkdir(parents=True, exist_ok=True)
        command += ["--capture-every", "1", "--capture-dir", str(frames_dir)]
    proc = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    (out / f"{name}.log").write_text(proc.stdout + proc.stderr)
    if proc.returncode:
        result["text"] = f"arklay exited {proc.returncode}: {proc.stderr.strip()[-200:]}"
        result["problems"].append("arklay failed")
        return result

    ref_f, ark_f = out / f"{name}.ref.f", out / f"{name}.ark.f"
    if run.get("keep_sound_3"):
        shutil.copy(ref_trace, ref_f)
        shutil.copy(ark_trace, ark_f)
    else:
        drop_sound_3(ref_trace, ref_f)
        drop_sound_3(ark_trace, ark_f)
    cmp = compare_traces(ref_f, ark_f, offset, run["fields"], run.get("ignore", []))
    ref_f.unlink()
    ark_f.unlink()
    text = trace_text(cmp)
    if cmp["ticks"] < ticks:
        # compare_pair stops at the shorter trace, so a short one would otherwise pass.
        result["problems"].append(f"only {cmp['ticks']} of {ticks} ticks compared (a trace ended early)")
    why = judge_trace(run, cmp)
    if why:
        result["problems"].append(why)
        result["notes"] += cmp["detail"]

    if run.get("frames"):
        if not want_frames:
            text += "; frames: no reference frames"
        else:
            first, last = run["frames"]
            boxes = [tuple(box) for box in run.get("boxes", [])]
            per_tick = frame_errors(ref_dir / "frames", frames_dir, first, last, offset, [])
            plain = frame_summary(per_tick)
            if plain["count"] == 0:
                result["problems"].append("no frames to compare")
            worst = " ".join(f"t{t}:{e:.2f}" for e, t in plain["worst"])
            text += f"; frames {plain['count']} mean {plain['mean']:.2f} worst {worst}"
            if boxes:
                boxed = frame_summary(frame_errors(ref_dir / "frames", frames_dir, first, last, offset, boxes))
                text += f" (box blanked {boxed['mean']:.2f})"
            limit = run.get("frame_max_mean")
            if limit is not None and plain["mean"] > limit:
                result["problems"].append(f"frame mean {plain['mean']:.2f} is over {limit}")
            if run.get("frame_windows"):
                texts, problems = judge_windows(run["frame_windows"], per_tick)
                text += "; windows " + ", ".join(texts)
                result["problems"].extend(problems)
        if not ctx["keep"]:
            shutil.rmtree(frames_dir, ignore_errors=True)
    if not ctx["keep"]:
        ark_trace.unlink(missing_ok=True)
    result["text"] = text
    return result


# ---------------------------------------------------------------- pack


def ensure_pack(args, out: Path) -> Path:
    if args.pack:
        pack = Path(args.pack).expanduser()
        if not pack.exists():
            raise SystemExit(f"re2-regress: pack {pack} does not exist")
        return pack
    pack = out / "re2.akpak"
    stamp = out / "re2.akpak.stamp"
    want = pack_stamp(args.arklay)
    if pack.exists() and stamp.exists() and stamp.read_text() == want:
        return pack
    game = args.game or os.environ.get("ARKLAY_RE2_ROOT")
    if not game:
        if pack.exists():
            print(f"re2-regress: {pack} may be stale (built by another arklay or from other game scripts); "
                  "pass --game to convert it again", flush=True)
            return pack
        raise SystemExit("re2-regress: no --pack, and no --game or ARKLAY_RE2_ROOT to convert one from")
    why = "once" if not pack.exists() else "again: the arklay binary or games/re2 changed"
    print(f"converting {game} to {pack} ({why})", flush=True)
    stamp.unlink(missing_ok=True)
    subprocess.run(
        [str(args.arklay), "convert-game", game, "--game", "re2", "--out", str(pack)],
        cwd=ROOT, check=True, stdout=subprocess.DEVNULL,
    )
    stamp.write_text(want)
    return pack


def pack_stamp(arklay: Path) -> str:
    """What a converted pack depends on in this checkout: the arklay binary that
    converted it (the converter) and every file under games/re2 (the scripts it
    packs). A pack whose stamp differs is converted again."""
    digest = hashlib.sha256()
    digest.update(Path(arklay).read_bytes())
    scripts = ROOT / "games" / "re2"
    for path in sorted(p for p in scripts.rglob("*") if p.is_file()):
        digest.update(str(path.relative_to(scripts)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest() + "\n"


def check_out(path: str) -> Path:
    out = Path(path).expanduser().resolve()
    for forbidden in (Path("/tmp"), Path("/var/tmp"), Path("/dev/shm")):
        if out == forbidden or forbidden in out.parents:
            raise SystemExit(f"re2-regress: --out {out} is in {forbidden}, a small RAM disk on the machines this runs on")
    out.mkdir(parents=True, exist_ok=True)
    return out


# ---------------------------------------------------------------- record


def record_run(run: dict, args, refs: Path) -> int:
    """Record the original for a run into the refs dir, with the meta.txt the other references have."""
    name = run["name"]
    if "record" not in run:
        print(f"{name}: the manifest has no record command for this run")
        return 1
    game = args.game or os.environ.get("ARKLAY_RE2_ROOT")
    if not game:
        print("record needs --game or ARKLAY_RE2_ROOT: the install holding bio2 1.10.exe")
        return 1
    dest = refs / run["ref"]
    if (dest / "ref.trace").exists() and not args.force:
        print(f"{name}: {dest / 'ref.trace'} exists (--force records it again)")
        return 1
    record_input = run.get("record_input") or run["input"].replace("_arklay", "")
    input_file = INPUTS / record_input
    work = Path(args.work).expanduser() if args.work else check_out(args.out) / "wine"
    command = [
        sys.executable, str(ROOT / "scripts" / "oracle-re2.py"), "record",
        "--game", game, "--work", str(work),
        "--input", str(input_file.relative_to(ROOT)),
        "--ticks", str(run["ticks"]), "--trace", str(dest / "ref.trace"),
    ]
    if run.get("sound", True):
        command.append("--sound")
    if run.get("ui", "game") != "game":
        command.append("--boot")
    if run.get("frames"):
        command += ["--shot-dir", str(dest / "frames"), "--shot-every", "1"]
    command += choice_args(run) + shlex.split(run["record"])
    if not args.dry_run:
        dest.mkdir(parents=True, exist_ok=True)
    print(f"{name}: " + " ".join(shlex.quote(part) for part in command), flush=True)
    if args.dry_run:
        return 0
    log = dest / "ref.log"
    with open(log, "w") as handle:
        code = subprocess.run(command, cwd=ROOT, stdout=handle, stderr=subprocess.STDOUT).returncode
    if code:
        print(f"{name}: the record failed (exit {code}, see {log})")
        return code
    trace = dest / "ref.trace"
    shown = [part if part != game else "$ARKLAY_RE2_ROOT" for part in command]
    shown = [part.replace(str(refs), "$ARKLAY_RE2_REFS").replace(str(work), "$WORK") for part in shown]
    shown[0] = "python3"
    shown[1] = "scripts/oracle-re2.py"
    meta = [
        f"name: {name}",
        f"recorded: {datetime.date.today().isoformat()}",
        f"input: {record_input}",
        f"input_sha256: {hashlib.sha256(input_file.read_bytes()).hexdigest()}",
        f"trace_md5: {hashlib.md5(trace.read_bytes()).hexdigest()}",
        "command: " + " ".join(shlex.quote(part) for part in shown),
    ]
    (dest / "meta.txt").write_text("\n".join(meta) + "\n")
    print(f"{name}: recorded into {dest}")
    return 0


# ---------------------------------------------------------------- main


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("names", nargs="*", help="`record` first to record, then run names (default: every run)")
    parser.add_argument("--out", required=True, help="output directory (not under /tmp)")
    parser.add_argument("--arklay", default=str(DEFAULT_ARKLAY), help="the arklay binary")
    parser.add_argument("--pack", default=None, help="an RE 2 pack; default: converted once into --out")
    parser.add_argument("--game", default=None, help="the RE 2 install (else ARKLAY_RE2_ROOT), to convert a pack or record")
    parser.add_argument("--refs", default=None, help=f"references dir (else ARKLAY_RE2_REFS, else {DEFAULT_REFS})")
    parser.add_argument("--manifest", default=str(MANIFEST))
    parser.add_argument("--jobs", type=int, default=3)
    parser.add_argument("--keep", action="store_true", help="keep arklay's frames and traces")
    parser.add_argument("--list", action="store_true", help="list the runs and whether their reference exists")
    parser.add_argument("--skip-missing", action="store_true", help="a missing reference is not a failure")
    parser.add_argument("--dry-run", action="store_true", help="record: print the command and stop")
    parser.add_argument("--force", action="store_true", help="record: replace an existing reference")
    parser.add_argument("--work", default=None, help="record: the Wine prefix dir (default: wine under --out)")
    if sys.argv[1:] == ["--self-test"]:
        return self_test()
    args = parser.parse_args()

    names = args.names
    record = bool(names) and names[0] == "record"
    if record:
        names = names[1:]
    _, runs = load_manifest(Path(args.manifest))
    known = {run["name"] for run in runs}
    unknown = [name for name in names if name not in known]
    if unknown:
        raise SystemExit(f"re2-regress: not in the manifest: {', '.join(unknown)}")
    if names:
        runs = [run for run in runs if run["name"] in names]
    out = check_out(args.out)
    refs = refs_dir(args)

    if record:
        if not names:
            raise SystemExit("re2-regress: record needs run names")
        return max(record_run(run, args, refs) for run in runs)

    if args.list:
        for run in runs:
            have = (refs / run["ref"] / "ref.trace").exists()
            frames = (refs / run["ref"] / "frames").is_dir()
            print(f"{run['name']:24} ref {'yes' if have else 'MISSING':7} frames {'yes' if frames else 'no'}")
        return 0

    args.arklay = Path(args.arklay).expanduser()
    if not args.arklay.exists():
        raise SystemExit(f"re2-regress: {args.arklay} does not exist (cargo build --profile test-release)")
    ctx = {"out": out, "refs": refs, "arklay": args.arklay.resolve(), "keep": args.keep}
    ctx["pack"] = ensure_pack(args, out).resolve()

    results = []
    with concurrent.futures.ThreadPoolExecutor(max(1, args.jobs)) as pool:
        for result in pool.map(lambda run: run_one(run, ctx), runs):
            status = "ok" if not result["problems"] else "UNEXPECTED: " + "; ".join(result["problems"])
            print(f"{result['name']:24} {result['text']}  [{status}]", flush=True)
            for note in result["notes"]:
                print(f"    {note}")
            results.append(result)

    bad = [r for r in results if r["problems"] and not (args.skip_missing and r.get("missing"))]
    print(f"\n{len(results) - len(bad)} of {len(results)} runs as expected" + (f"; unexpected: {', '.join(r['name'] for r in bad)}" if bad else ""))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
