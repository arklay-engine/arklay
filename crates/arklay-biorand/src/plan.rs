//! The generator's top level: [`generate`] runs every stage in staging's
//! order (`ClassicRandomizer.Randomize`, `ClassicRandomizer.cs:716-757`) and
//! returns the [`Plan`] the engine crate applies to a pack.
//!
//! The stages, each with its own named random stream, so that what one stage
//! draws never shifts another:
//!
//! | Stage | Stream | Runs when |
//! |---|---|---|
//! | [`config::resolve`] | `config` | always |
//! | [`prepare::prepare`] | `re1map` | always |
//! | [`inventory::randomize`] | `inventory` | always |
//! | doors (later) | `sourceDoor` | `doors/random` |
//! | [`locks::randomize`] | `lock` | `locks/random` |
//! | [`keys::randomize`] | `key` | `items/random` |
//! | [`items::randomize`] | `item` | `items/random` |
//! | [`enemies::randomize`] | `enemy` | `enemies/random` |
//!
//! Door randomization is a later milestone. Until it comes, [`generate`]
//! turns `doors/random` off and lists it in [`Game::deferred`]; the game
//! keeps the original doors.

use std::collections::HashMap;

use anyhow::{Context, Result, bail};
use indexmap::IndexMap;
use serde_json::{Value as Json, json};

use crate::config::{self, Config};
use crate::enemies::{self, EnemyPlan};
use crate::inventory::{self, StartInventory};
use crate::items::{self, Pickup};
use crate::keys::{self, KeyOptions, KeyPlacement};
use crate::locks::{self, DoorLock};
use crate::map::{Map, Player};
use crate::prepare::{self, Progression};
use crate::rng::Rng;

/// Bumped whenever a seed's plan changes, so a pack generated by an older
/// version is known to be stale.
pub const GENERATOR_VERSION: u32 = 2;

/// The BioRand system flags in bank 5, by the names the engine's scripts and
/// manifests give them (`arklay::scd::opcode::system::BY_NAME`).
pub mod system_flags {
    /// Any generated game. The engine also raises it for a manifest's seed.
    pub const RANDOMIZER: &str = "RANDOMIZER";
    pub const DOOR_RANDOMIZER: &str = "DOOR_RANDOMIZER";
    pub const ENEMY_RANDOMIZER: &str = "ENEMY_RANDOMIZER";
    pub const ITEM_RANDOMIZER: &str = "ITEM_RANDOMIZER";
    pub const LOCK_RANDOMIZER: &str = "LOCK_RANDOMIZER";
    pub const CUTSCENES_DISABLED: &str = "CUTSCENES_DISABLED";
    pub const FORCE_TYRANT2: &str = "FORCE_TYRANT2";
    /// The game reaches the laboratory.
    pub const LAB: &str = "LAB";
    pub const BR_LOCK_FULL_BYTE: &str = "BR_LOCK_FULL_BYTE";
    pub const BR_NEPTUNE_KILLABLE: &str = "BR_NEPTUNE_KILLABLE";
    pub const BR_YAWN_POISON: &str = "BR_YAWN_POISON";
    pub const BR_HERB_MIXES: &str = "BR_HERB_MIXES";
    pub const BR_INK_FLAG: &str = "BR_INK_FLAG";
    pub const BR_NO_TITLE_DEMO: &str = "BR_NO_TITLE_DEMO";

    /// The executable patches staging's mod applies to every game
    /// (`docs/biorand/patches.md` section A). Staging also always writes the
    /// whole lock byte; here [`BR_LOCK_FULL_BYTE`] comes with
    /// `locks/random`, the only stage that writes lock bytes, and a game on
    /// the original locks reads them the original's way.
    pub const ALWAYS: [&str; 5] = [
        BR_NEPTUNE_KILLABLE,
        BR_YAWN_POISON,
        BR_HERB_MIXES,
        BR_INK_FLAG,
        BR_NO_TITLE_DEMO,
    ];
}

/// Which players' games to plan.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Players {
    /// The configuration's `player`, drawn when it is `Random`, as staging
    /// plays.
    Configured,
    /// One player, whatever the configuration says.
    Only(Player),
    /// Chris's game and Jill's, each planned on its own.
    Both,
}

/// A generated game, ready to apply to a pack.
#[derive(Clone, Debug, PartialEq)]
pub struct Plan {
    /// The seed every stream was named from.
    pub seed: u64,
    /// [`GENERATOR_VERSION`] when the plan was made.
    pub version: u32,
    /// One game per player planned: Chris's first under [`Players::Both`].
    pub games: Vec<Game>,
}

/// One player's game.
#[derive(Clone, Debug, PartialEq)]
pub struct Game {
    pub player: Player,
    /// The configuration the stages read: the input resolved as staging
    /// resolves it ([`config::resolve`]), with the deferred options off.
    pub config: Config,
    /// Options the configuration turns on that this generator doesn't apply
    /// yet (`doors/random`). The game is planned without them.
    pub deferred: Vec<String>,
    /// The system flags (bank 5) the pack raises at the start of a game and
    /// when a save loads, by name. See [`system_flags`].
    pub system_flags: Vec<&'static str>,
    /// The scenario flags the options set at the start of a game.
    pub scenario_flags: Vec<ScenarioFlag>,
    /// How many inventory slots each character has.
    pub inventory_sizes: InventorySizes,
    /// The player's starting inventory, cut to their slot count.
    pub inventory: StartInventory,
    /// What each item slot holds, by room directory in lowercase (`10c`),
    /// then by the AOT id of its `item_aot_set`, in map order. Every slot of
    /// every room in the game is here. Rooms the game leaves out (the
    /// guardhouse or the lab, by the progression options) are not, and keep
    /// the original's pickups.
    pub items: IndexMap<String, IndexMap<u8, SlotPlan>>,
    /// Where the key stage put the keys, with the route finder's log. `None`
    /// when items aren't randomized.
    pub keys: Option<KeyPlacement>,
    /// The enemy changes; empty when enemies aren't randomized.
    pub enemies: EnemyPlan,
    /// Every door's lock, in map order, when locks are randomized (empty
    /// otherwise): the whole lock byte and the key byte the pack writes into
    /// its `door_aot_set`, both sides of a pair sharing the lock flag. See
    /// [`DoorLock`].
    pub locks: Vec<DoorLock>,
    /// What a player may read to find their way: see [`Spoiler`].
    pub spoiler: Spoiler,
}

/// A scenario flag (bank 0) an option sets, as staging's room 106 sets it
/// (`Re1RdtPatcher.ConfigureOptions`). The engine raises the flag when
/// `raised` and clears it otherwise.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ScenarioFlag {
    /// The flag's index in bank 0.
    pub flag: u8,
    /// What it stands for: `ink`, `hard` or `lockpick`.
    pub name: &'static str,
    /// Whether the option is on.
    pub raised: bool,
}

/// Each character's inventory slot count (`inventory/size`, BioRand's
/// executable patch 22). The player has the configured count; the others keep
/// the original's.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct InventorySizes {
    pub chris: u8,
    pub jill: u8,
    pub rebecca: u8,
}

impl InventorySizes {
    /// The original game's counts.
    pub const ORIGINAL: Self = Self {
        chris: 6,
        jill: 8,
        rebecca: 6,
    };

    pub fn of(&self, player: Player) -> u8 {
        match player {
            Player::Chris => self.chris,
            Player::Jill => self.jill,
        }
    }
}

/// One item slot of a room.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SlotPlan {
    /// The slot's pickup flag in `FG_ITEM` (staging's `globalId`). Two slots
    /// sharing one always hold the same.
    pub flag: u16,
    /// The logical room the slot is in (`10C/BACK`).
    pub room: String,
    /// The room file's name for the slot, for logs.
    pub name: Option<String>,
    /// What it holds.
    pub pickup: Pickup,
}

/// Plans a game from `map` (every room's `random.xml` and the map-wide file,
/// as read) and the configuration the player chose, unresolved. The same
/// inputs always give the same plan.
pub fn generate(map: &Map, config: &Config, seed: u64, players: Players) -> Result<Plan> {
    let definition = config::definition(map);
    let resolve = |player: Option<Player>| {
        let mut config = config.clone();
        if let Some(player) = player {
            config.set("player", player_name(player));
        }
        config::resolve(&definition, &config, &mut Rng::named(seed, "config"))
    };
    let configs = match players {
        Players::Configured => vec![resolve(None)],
        Players::Only(player) => vec![resolve(Some(player))],
        Players::Both => vec![resolve(Some(Player::Chris)), resolve(Some(Player::Jill))],
    };
    let games = configs
        .into_iter()
        .map(|config| {
            let player = match config.get_str("player", "Chris").as_str() {
                "Chris" => Player::Chris,
                "Jill" => Player::Jill,
                other => bail!("unknown player {other:?}"),
            };
            plan_game(map, config, seed, player)
                .with_context(|| format!("{} seed {seed}", player_name(player)))
        })
        .collect::<Result<_>>()?;
    Ok(Plan {
        seed,
        version: GENERATOR_VERSION,
        games,
    })
}

fn player_name(player: Player) -> &'static str {
    match player {
        Player::Chris => "Chris",
        Player::Jill => "Jill",
    }
}

/// The stages for one player, in staging's order.
fn plan_game(map: &Map, mut config: Config, seed: u64, player: Player) -> Result<Game> {
    let mut deferred = Vec::new();
    // Door randomization is a later milestone.
    if config.get_bool("doors/random", false) {
        config.set("doors/random", false);
        deferred.push("doors/random".to_string());
    }

    let options = prepare::Options::from_config(&config, player);
    let map = prepare::prepare(map, &options, &mut Rng::named(seed, "re1map"))?;

    let inventory_sizes = inventory_sizes(&config, player);
    let mut inventory =
        inventory::randomize(&map, &config, player, &mut Rng::named(seed, "inventory"));
    fit_inventory(&mut inventory, inventory_sizes.of(player));

    // Hook (door milestone): the door randomizer, stream `sourceDoor`, under
    // `doors/random`. It returns the map with its doors rewired.

    let (map, locks) = locks::randomize(&map, &config, &mut Rng::named(seed, "lock"))?;

    let randomize_items = config.get_bool("items/random", false);
    let (keys, item_plan) = if randomize_items {
        let key_options = KeyOptions::from_config(&config, player);
        let keys = keys::randomize(&map, &key_options, &mut Rng::named(seed, "key"))?;
        if !keys.all_nodes_visited {
            // Staging uses a partial route as it is; a game that can't be
            // finished is an error here.
            bail!("the route finder left part of the map unreachable");
        }
        let item_plan = items::randomize(
            &map,
            &config,
            &inventory,
            &keys,
            &mut Rng::named(seed, "item"),
        )?;
        (Some(keys), item_plan)
    } else {
        (None, items::ItemPlan::default())
    };
    let items = room_slots(&map, &item_plan)?;

    let rooms = map.rooms.keys().cloned().collect();
    let enemies = enemies::randomize(
        &map,
        &config,
        player,
        &rooms,
        &mut Rng::named(seed, "enemy"),
    );

    let progression = Progression::from_config(&config);
    let mut game = Game {
        player,
        system_flags: system_flags_for(&config, &progression),
        scenario_flags: scenario_flags(&config),
        inventory_sizes,
        inventory,
        items,
        keys,
        enemies,
        locks,
        deferred,
        config,
        spoiler: Spoiler::default(),
    };
    game.spoiler = Spoiler::new(&map, seed, &game);
    Ok(game)
}

/// Staging's `ApplyModGeneral` (`Re1ClassicRandomizerController.cs:614`):
/// `"6"` is six slots and anything else eight.
fn inventory_sizes(config: &Config, player: Player) -> InventorySizes {
    let size = if config.get_str("inventory/size", "8") == "6" {
        6
    } else {
        8
    };
    let mut sizes = InventorySizes::ORIGINAL;
    match player {
        Player::Chris => sizes.chris = size,
        Player::Jill => sizes.jill = size,
    }
    sizes
}

/// Drops the stacks that don't fit in `size` slots, as staging's emitter
/// does (`RandomInventory.WithSize`), and the weapons among them. Staging's
/// item stage still counts a dropped weapon as held; here the plan says
/// exactly what the player starts with, and the item stage reads that.
fn fit_inventory(inventory: &mut StartInventory, size: u8) {
    inventory.slots.truncate(usize::from(size));
    let kept: Vec<u8> = inventory.slots.iter().map(|slot| slot.item).collect();
    inventory.weapons.retain(|weapon| kept.contains(weapon));
}

/// The plan's slots by room directory and AOT id. Fails if two slots of a
/// directory share an AOT id but not a pickup flag, which an emitter
/// couldn't tell apart.
fn room_slots(
    map: &Map,
    plan: &items::ItemPlan,
) -> Result<IndexMap<String, IndexMap<u8, SlotPlan>>> {
    let mut rooms: IndexMap<String, IndexMap<u8, SlotPlan>> = IndexMap::new();
    for room in map.rooms.values() {
        let dir = room.room_id().to_ascii_lowercase();
        for item in &room.items {
            let Some(flag) = item.flag else {
                continue;
            };
            let slot = SlotPlan {
                flag,
                room: room.key.clone(),
                name: item.name.clone(),
                pickup: plan.slots.get(&flag).copied().unwrap_or(Pickup::Original),
            };
            let slots = rooms.entry(dir.clone()).or_default();
            match slots.get(&item.id) {
                Some(other) if other.flag != flag => bail!(
                    "room {dir}: AOT {} is both pickup flag {} and {flag}",
                    item.id,
                    other.flag
                ),
                Some(_) => {}
                None => {
                    slots.insert(item.id, slot);
                }
            }
        }
    }
    Ok(rooms)
}

fn system_flags_for(config: &Config, progression: &Progression) -> Vec<&'static str> {
    use system_flags::*;
    let mut flags = vec![RANDOMIZER];
    let options = [
        (config.get_bool("doors/random", false), DOOR_RANDOMIZER),
        (config.get_bool("enemies/random", false), ENEMY_RANDOMIZER),
        (config.get_bool("items/random", false), ITEM_RANDOMIZER),
        (config.get_bool("locks/random", false), LOCK_RANDOMIZER),
        (config.get_bool("locks/random", false), BR_LOCK_FULL_BYTE),
        (
            config.get_bool("cutscenes/disable", false),
            CUTSCENES_DISABLED,
        ),
        (
            config.get_str("progression/tyrant2", "Never") == "Always",
            FORCE_TYRANT2,
        ),
        (progression.lab, LAB),
    ];
    flags.extend(options.iter().filter(|(on, _)| *on).map(|(_, flag)| *flag));
    flags.extend(ALWAYS);
    flags
}

/// `Re1RdtPatcher.ConfigureOptions`: ink 122, hard 123, lockpick 124.
fn scenario_flags(config: &Config) -> Vec<ScenarioFlag> {
    let flag = |flag, name, raised| ScenarioFlag { flag, name, raised };
    vec![
        flag(
            122,
            "ink",
            config.get_str("ink/enable", "Always") == "Always",
        ),
        flag(123, "hard", config.get_bool("hard", false)),
        flag(
            124,
            "lockpick",
            config.get_str("inventory/special/lockpick", "Always") == "Always",
        ),
    ]
}

/// The spoiler log of a game: the start, where every key is, and every room's
/// pickups and enemies. [`Spoiler::to_json`] and [`Spoiler::to_text`] write it.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Spoiler {
    pub player: Option<Player>,
    pub seed: u64,
    /// The deferred options, which the game doesn't apply.
    pub deferred: Vec<String>,
    /// The starting inventory: item names and amounts.
    pub inventory: Vec<(String, u16)>,
    /// Each key, in the order the route finder placed them.
    pub keys: Vec<SpoilerPickup>,
    /// The doors a key opens, one per pair, when locks are randomized.
    pub locks: Vec<SpoilerLock>,
    /// Every room with a pickup or an enemy change, in map order.
    pub rooms: Vec<SpoilerRoom>,
}

/// A room in the spoiler log.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SpoilerRoom {
    /// The logical room key, such as `10C/BACK`.
    pub key: String,
    pub name: String,
    pub pickups: Vec<SpoilerPickup>,
    /// The enemies added or retyped: kind and how many.
    pub enemies: Option<(String, usize)>,
}

/// A locked door in the spoiler log.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SpoilerLock {
    /// `room:id` of one side.
    pub door: String,
    /// `room:id` of the other side, when the map has it.
    pub other: Option<String>,
    /// The name of the key that opens it.
    pub key: String,
}

/// A slot and what it holds, by name.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SpoilerPickup {
    /// `room key|room name/slot name`, as the route finder labels slots.
    pub location: String,
    /// The slot's name in its room.
    pub slot: String,
    /// The item's name, `(original)` or `(nothing)`.
    pub item: String,
    pub amount: u16,
    /// `key`, `weapon`, `supply`, `original` or `empty`.
    pub role: &'static str,
}

impl Spoiler {
    fn new(map: &Map, seed: u64, game: &Game) -> Self {
        let item_name = |id: u8| {
            map.items
                .get(&id)
                .map_or_else(|| format!("item {id}"), |def| def.name.clone())
        };
        let mut rooms: Vec<SpoilerRoom> = Vec::new();
        let mut ids: Vec<Vec<(u8, SpoilerPickup)>> = Vec::new();
        for room in map.rooms.values() {
            let dir = room.room_id().to_ascii_lowercase();
            let room_name = room.name.clone().unwrap_or_default();
            let mut pickups = Vec::new();
            for item in &room.items {
                let Some(slot) = game.items.get(&dir).and_then(|slots| slots.get(&item.id)) else {
                    continue;
                };
                if slot.room != room.key {
                    continue;
                }
                let slot_name = item
                    .name
                    .clone()
                    .unwrap_or_else(|| format!("AOT {}", item.id));
                let (name, amount, role) = match slot.pickup {
                    Pickup::Original => ("(original)".to_string(), 0, "original"),
                    Pickup::Empty => ("(nothing)".to_string(), 0, "empty"),
                    Pickup::Item { item, amount, role } => (item_name(item), amount, role.as_str()),
                };
                pickups.push((
                    item.id,
                    SpoilerPickup {
                        location: format!("{}|{room_name}/{slot_name}", room.key),
                        slot: slot_name,
                        item: name,
                        amount,
                        role,
                    },
                ));
            }
            let enemies = game
                .enemies
                .rooms
                .get(&room.key)
                .map(|planned| (planned.kind.clone(), planned.placements.len()));
            if !pickups.is_empty() || enemies.is_some() {
                rooms.push(SpoilerRoom {
                    key: room.key.clone(),
                    name: room_name,
                    pickups: pickups.iter().map(|(_, pickup)| pickup.clone()).collect(),
                    enemies,
                });
            }
            ids.push(pickups);
        }
        // Each logical room's pickups by AOT id, to find the keys' slots.
        let by_slot: HashMap<(&str, u8), &SpoilerPickup> = map
            .rooms
            .values()
            .zip(&ids)
            .flat_map(|(room, pickups)| {
                pickups
                    .iter()
                    .map(move |(id, pickup)| ((room.key.as_str(), *id), pickup))
            })
            .collect();
        let keys = game
            .keys
            .iter()
            .flat_map(|keys| &keys.keys)
            .filter_map(|placed| by_slot.get(&(placed.slot.room.as_str(), placed.slot.item)))
            .map(|&pickup| pickup.clone())
            .collect();
        let mut locks: Vec<SpoilerLock> = Vec::new();
        for door in &game.locks {
            let Some(key) = door.key_item() else {
                continue;
            };
            let name = format!("{}:{}", door.room, door.id);
            if locks
                .iter()
                .any(|lock| lock.other.as_deref() == Some(name.as_str()))
            {
                continue;
            }
            locks.push(SpoilerLock {
                door: name,
                other: door.other.clone(),
                key: item_name(key),
            });
        }
        Self {
            player: Some(game.player),
            seed,
            deferred: game.deferred.clone(),
            locks,
            inventory: game
                .inventory
                .slots
                .iter()
                .map(|slot| (item_name(slot.item), slot.amount))
                .collect(),
            keys,
            rooms,
        }
    }

    /// The log as JSON.
    pub fn to_json(&self) -> Json {
        let pickup = |p: &SpoilerPickup| {
            json!({
                "location": p.location,
                "slot": p.slot,
                "item": p.item,
                "amount": p.amount,
                "role": p.role,
            })
        };
        json!({
            "player": self.player.map(player_name),
            "seed": self.seed,
            "deferred": self.deferred,
            "inventory": self.inventory.iter().map(|(item, amount)| json!({"item": item, "amount": amount})).collect::<Vec<_>>(),
            "keys": self.keys.iter().map(pickup).collect::<Vec<_>>(),
            "locks": self.locks.iter().map(|lock| json!({"door": lock.door, "other": lock.other, "key": lock.key})).collect::<Vec<_>>(),
            "rooms": self.rooms.iter().map(|room| json!({
                "key": room.key,
                "name": room.name,
                "pickups": room.pickups.iter().map(pickup).collect::<Vec<_>>(),
                "enemies": room.enemies.as_ref().map(|(kind, count)| json!({"kind": kind, "count": count})),
            })).collect::<Vec<_>>(),
        })
    }

    /// The log as text, for a player to read.
    pub fn to_text(&self) -> String {
        use std::fmt::Write;
        let mut text = String::new();
        let player = self.player.map_or("?", player_name);
        let _ = writeln!(text, "BioRand seed {} ({player})", self.seed);
        if !self.deferred.is_empty() {
            let _ = writeln!(text, "Not applied yet: {}", self.deferred.join(", "));
        }
        let _ = writeln!(text, "\nStarting inventory:");
        for (item, amount) in &self.inventory {
            let _ = writeln!(text, "  {item} x{amount}");
        }
        if !self.keys.is_empty() {
            let _ = writeln!(text, "\nKeys:");
            for key in &self.keys {
                let _ = writeln!(text, "  {}: {} x{}", key.location, key.item, key.amount);
            }
        }
        if !self.locks.is_empty() {
            let _ = writeln!(text, "\nLocked doors:");
            for lock in &self.locks {
                let other = lock.other.as_deref().unwrap_or("?");
                let _ = writeln!(text, "  {} <-> {other}: {}", lock.door, lock.key);
            }
        }
        let _ = writeln!(text, "\nRooms:");
        for room in &self.rooms {
            let _ = writeln!(text, "  {} {}", room.key, room.name);
            if let Some((kind, count)) = &room.enemies {
                let _ = writeln!(text, "    enemies: {count} {kind}");
            }
            for pickup in &room.pickups {
                match pickup.role {
                    "original" | "empty" => {
                        let _ = writeln!(text, "    {}: {}", pickup.slot, pickup.item);
                    }
                    role => {
                        let _ = writeln!(
                            text,
                            "    {}: {} x{} ({role})",
                            pickup.slot, pickup.item, pickup.amount
                        );
                    }
                }
            }
        }
        text
    }
}
