/// Compile the checked-in room scripts under `games/re1/room/` into the SCD
/// bytecode `convert-game` packs as each room's `room.scd`: one runtime build
/// per room, which carries every RDT variant and region and picks between
/// them as it runs.
fn emit_room_scripts() {
    use scd::akscr::preprocess::{Build, ROOM_SCRIPT_FILE, includes_from, room_script_file};

    let root = manifest_dir().join("games/re1/room");
    for watched in [
        "games/re1/room",
        "games/re1/inc",
        "src/scd",
        "src/budget.rs",
        "build",
    ] {
        println!("cargo:rerun-if-changed={watched}");
    }

    // Each room's script sits in its room's folder (`103/room.akscr`).
    let mut scripts: Vec<(u16, PathBuf)> = Vec::new();
    let read = std::fs::read_dir(&root).unwrap_or_else(|err| {
        panic!(
            "cannot read room script directory {}: {err}",
            root.display()
        )
    });
    for entry in read.flatten() {
        let path = entry.path().join(ROOM_SCRIPT_FILE);
        if !path.is_file() {
            continue;
        }
        let name = entry.file_name();
        let base = name
            .to_str()
            .filter(|name| name.len() == 3)
            .and_then(|name| u16::from_str_radix(name, 16).ok())
            .unwrap_or_else(|| panic!("{} is not in a room's folder", path.display()));
        assert_eq!(
            root.join(room_script_file(base)),
            path,
            "{} is not in its room's folder",
            path.display()
        );
        scripts.push((base, path));
    }
    scripts.sort();
    assert!(
        !scripts.is_empty(),
        "no room scripts found under {}; the build would ship an empty ROOM_SCRIPTS",
        root.display()
    );

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let scd_dir = out_dir.join("room_scd");
    std::fs::create_dir_all(&scd_dir).expect("failed to create the room bytecode directory");
    let load = includes_from(&root);
    let compile = |text: &str, build: Build, path: &PathBuf| {
        scd::akscr::compile::compile_build(text, build, &load)
            .and_then(|assembled| assembled.to_container())
            .unwrap_or_else(|err| panic!("{} ({build:?}): {err:#}", path.display()))
    };

    // One room's table line. Compiling every room is a few seconds of work on
    // one core, and every lib build waits for it, so the rooms are spread
    // over the cores below (#266).
    let emit = |base: u16, path: &PathBuf| {
        let text = std::fs::read_to_string(path)
            .unwrap_or_else(|err| panic!("cannot read {}: {err}", path.display()));
        let container = compile(&text, Build::Runtime, path);
        let file = scd_dir.join(format!("{base:03x}.scd"));
        std::fs::write(&file, &container).expect("failed to write room bytecode");
        format!(
            "    RoomScript {{ room: 0x{base:03X}, container: include_bytes!({:?}) }},\n",
            file.to_string_lossy()
        )
    };
    let threads = std::thread::available_parallelism().map_or(1, |n| n.get());
    let rooms: Vec<String> = std::thread::scope(|scope| {
        let workers: Vec<_> = scripts
            .chunks(scripts.len().div_ceil(threads))
            .map(|chunk| {
                let emit = &emit;
                scope.spawn(move || {
                    chunk
                        .iter()
                        .map(|(base, path)| emit(*base, path))
                        .collect::<Vec<_>>()
                })
            })
            .collect();
        workers
            .into_iter()
            .flat_map(|worker| {
                worker
                    .join()
                    .unwrap_or_else(|panic| std::panic::resume_unwind(panic))
            })
            .collect()
    });

    let mut out = String::from(
        "// @generated by build.rs from games/re1/room: each room's compiled scripts.\n&[\n",
    );
    out.extend(rooms);
    out.push_str("]\n");
    std::fs::write(out_dir.join("room_scripts.rs"), out)
        .expect("failed to write the generated room script table");
}

/// Generate the table of the checked-in RE1 room definitions under
/// `games/re1/room/`: every `<id>/` folder's XML files (`room.xml` and its
/// `effect/<slot>.xml`). `convert-game` packs them in place of anything read
/// from the install's RDTs.
fn emit_room_files() {
    fn walk(dir: &Path, root: &Path, files: &mut Vec<(String, PathBuf)>) {
        let read = std::fs::read_dir(dir)
            .unwrap_or_else(|err| panic!("cannot read room directory {}: {err}", dir.display()));
        for entry in read.flatten() {
            let path = entry.path();
            if path.is_dir() {
                walk(&path, root, files);
            } else if path.extension().is_some_and(|ext| ext == "xml") {
                let relative = path
                    .strip_prefix(root)
                    .expect("walked paths are under the root")
                    .to_string_lossy()
                    .replace('\\', "/");
                files.push((relative, path));
            }
        }
    }

    // `emit_room_scripts` already watches `games/re1/room`.
    let root = manifest_dir().join("games/re1/room");
    let mut files = Vec::new();
    walk(&root, &root, &mut files);
    files.sort();
    assert!(
        files.iter().any(|(path, _)| path.ends_with("/room.xml")),
        "no room definitions found under {}; the build would ship an empty ROOM_FILES",
        root.display()
    );

    // Most player variants (and the European copies of unchanged effect
    // definitions) are the same file, so each distinct text is embedded once.
    let mut texts: Vec<(String, &PathBuf)> = Vec::new();
    let mut table = Vec::new();
    for (relative, path) in &files {
        let text = std::fs::read_to_string(path)
            .unwrap_or_else(|err| panic!("cannot read {}: {err}", path.display()));
        let index = match texts.iter().position(|(seen, _)| *seen == text) {
            Some(index) => index,
            None => {
                texts.push((text, path));
                texts.len() - 1
            }
        };
        table.push((relative, index));
    }

    let mut out = String::from(
        "// @generated by build.rs from games/re1/room: the checked-in room\n\
         // definitions, by path under that directory.\n",
    );
    for (index, (_, path)) in texts.iter().enumerate() {
        writeln!(
            out,
            "static TEXT_{index}: &str = include_str!({:?});",
            path.to_string_lossy()
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str("pub static ROOM_FILES: &[(&str, &str)] = &[\n");
    for (relative, index) in &table {
        writeln!(out, "    ({relative:?}, TEXT_{index}),")
            .expect("writing to a String cannot fail");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out_dir.join("room_files.rs"), out)
        .expect("failed to write the generated room definition table");
}
