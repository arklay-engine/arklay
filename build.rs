use std::fmt::Write as _;
use std::path::PathBuf;

// The room scripts compile with the crate's own compiler.
#[path = "src/budget.rs"]
#[allow(dead_code)]
mod budget;
#[path = "build/scd/mod.rs"]
mod scd;

/// The crate root, read at build-script run time.
///
/// Cargo sets `CARGO_MANIFEST_DIR` for the build script's process. Reading it
/// with `env!` would bake the path of whichever checkout compiled the build
/// script into the binary: a target directory reused by a worktree can then
/// run the old script against a path that no longer exists, silently emitting
/// empty tables. Runtime lookup keeps the generated pack entries tied to the
/// crate being built.
fn manifest_dir() -> PathBuf {
    PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR")
            .expect("cargo sets CARGO_MANIFEST_DIR for build scripts"),
    )
}

fn main() {
    println!("cargo:rerun-if-env-changed=SDL3_DIR");
    println!("cargo:rerun-if-changed=../vendor/sdl3");

    // Prefer an explicit SDL3_DIR, then the workspace vendor directory
    // (<workspace>/vendor/sdl3, one level above this crate). When neither
    // exists, sdl3-sys falls back to the system SDL3.
    let dir = std::env::var_os("SDL3_DIR")
        .map(PathBuf::from)
        .filter(|p| p.join("lib").is_dir())
        .or_else(|| {
            let vendor = PathBuf::from("../vendor/sdl3");
            vendor.join("lib").is_dir().then_some(vendor)
        });

    if let Some(dir) = dir {
        // Absolute paths keep the link search and rpath valid no matter where
        // the binary is run from.
        let dir = std::fs::canonicalize(&dir).unwrap_or(dir);
        let lib = dir.join("lib");
        println!("cargo:rustc-link-search=native={}", lib.display());
        println!("cargo:rustc-link-lib=dylib=SDL3");
        if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
            println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());
        }
    } else if let Some(out_dir) = std::env::var_os("DEP_SDL3_OUT_DIR") {
        // sdl3-sys built SDL3 from source (`build-from-source`) into its
        // OUT_DIR and copies the shared library to the profile directory for
        // runtime lookup. That copy is a loose file, so tooling such as
        // rust-cache prunes it while keeping the build output, leaving a
        // cached binary unable to load libSDL3.so.0. Point the binary straight
        // at the build output so the libraries the engine links against are
        // always found.
        if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
            let lib = PathBuf::from(out_dir).join("lib");
            if lib.join("libSDL3.so.0").is_file() {
                println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());
            }
        }
    }

    emit_scripts("enemy", "ENEMY_SCRIPTS", "enemy_scripts.rs");
    emit_scripts("ui", "UI_SCRIPTS", "ui_scripts.rs");
    emit_scripts("game", "GAME_SCRIPTS", "game_scripts.rs");
    emit_language_files();
    emit_room_scripts();
}

/// Generate the pack-entry table for the checked-in Lua scripts under
/// `games/re1/{dir}/`, so `convert-game` packs exactly the scripts in the tree
/// without a hand-maintained list.
fn emit_scripts(dir: &str, table: &str, file: &str) {
    let root = manifest_dir().join(format!("games/re1/{dir}"));
    println!("cargo:rerun-if-changed=games/re1/{dir}");

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    collect_lua(&root, dir, &mut entries);
    entries.sort_by_key(|(entry, _)| entry.to_ascii_lowercase());
    assert!(
        !entries.is_empty(),
        "no Lua scripts found under {}; the build would ship an empty {table}",
        root.display()
    );

    let mut out = format!(
        "// @generated by build.rs from games/re1/{dir}: the pack entries for\n\
         // the checked-in scripts.\n\
         pub static {table}: &[(&str, &str)] = &[\n"
    );
    for (entry, path) in &entries {
        writeln!(
            out,
            "    ({entry:?}, include_str!({:?})),",
            path.to_string_lossy()
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out_dir.join(file), out).expect("failed to write a generated script table");
}

/// Recursively collect every `.lua` file under `dir`, naming each pack entry
/// with the `prefix` path in `/` separators.
fn collect_lua(dir: &PathBuf, prefix: &str, entries: &mut Vec<(String, PathBuf)>) {
    let read = std::fs::read_dir(dir)
        .unwrap_or_else(|err| panic!("cannot read Lua script directory {}: {err}", dir.display()));
    for entry in read.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect_lua(&path, &format!("{prefix}/{name}"), entries);
        } else if name.to_ascii_lowercase().ends_with(".lua") {
            entries.push((format!("{prefix}/{name}"), path));
        }
    }
}

/// Generate the pack-entry table for the checked-in language sources under
/// `games/re1/language/`, so `convert-game` packs exactly the files in the
/// tree and can parse each one before it ships.
fn emit_language_files() {
    let root = manifest_dir().join("games/re1/language");
    println!("cargo:rerun-if-changed=games/re1/language");

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    let read = std::fs::read_dir(&root)
        .unwrap_or_else(|err| panic!("cannot read language directory {}: {err}", root.display()));
    for entry in read.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') || !path.is_file() {
            continue;
        }
        if name.to_ascii_lowercase().ends_with(".txt") {
            entries.push((format!("language/{name}"), path));
        }
    }
    entries.sort_by_key(|(entry, _)| entry.to_ascii_lowercase());
    assert!(
        !entries.is_empty(),
        "no language files found under {}; the build would ship an empty LANGUAGE_FILES",
        root.display()
    );

    let mut out = String::from(
        "// @generated by build.rs from games/re1/language: the pack entries for\n\
         // the checked-in language files.\n\
         pub static LANGUAGE_FILES: &[(&str, &str)] = &[\n",
    );
    for (entry, path) in &entries {
        writeln!(
            out,
            "    ({entry:?}, include_str!({:?})),",
            path.to_string_lossy()
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out_dir.join("language_files.rs"), out)
        .expect("failed to write the generated language-file table");
}

/// Compile the checked-in room scripts under `games/re1/room/` into the SCD
/// bytecode `convert-game` packs as `scd/<id>.scd`, one container per RDT
/// variant, each beside the digest of its `AUTHENTIC` build: a container only
/// replaces an RDT's own scripts when that digest proves they are the ones
/// the script was written from.
fn emit_room_scripts() {
    use scd::akscr::preprocess::{Variant, includes_from, room_variants};

    let root = manifest_dir().join("games/re1/room");
    for watched in [
        "games/re1/room",
        "games/re1/inc",
        "src/scd",
        "src/budget.rs",
        "build",
    ] {
        println!("cargo:rerun-if-changed={watched}");
    }

    let mut scripts: Vec<(u16, PathBuf)> = Vec::new();
    let read = std::fs::read_dir(&root).unwrap_or_else(|err| {
        panic!(
            "cannot read room script directory {}: {err}",
            root.display()
        )
    });
    for entry in read.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        let Some(stem) = name.to_str().and_then(|name| name.strip_suffix(".akscr")) else {
            continue;
        };
        let base = u16::from_str_radix(stem, 16)
            .unwrap_or_else(|_| panic!("{} is not named by its room id", path.display()));
        scripts.push((base, path));
    }
    scripts.sort();
    assert!(
        !scripts.is_empty(),
        "no room scripts found under {}; the build would ship an empty ROOM_SCRIPTS",
        root.display()
    );

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let scd_dir = out_dir.join("room_scd");
    std::fs::create_dir_all(&scd_dir).expect("failed to create the room bytecode directory");
    let load = includes_from(&root);
    let compile = |text: &str, variant: Variant, path: &PathBuf| {
        scd::akscr::compile::compile_with(text, Some(variant), &load)
            .and_then(|assembled| assembled.to_container())
            .unwrap_or_else(|err| panic!("{}: {err:#}", path.display()))
    };

    let mut out = String::from(
        "// @generated by build.rs from games/re1/room: each RDT's compiled scripts.\n&[\n",
    );
    for (base, path) in &scripts {
        let text = std::fs::read_to_string(path)
            .unwrap_or_else(|err| panic!("cannot read {}: {err}", path.display()));
        for id in room_variants(*base) {
            let variant = Variant::for_room(id);
            let authentic = compile(&text, variant.authentic(), path);
            let original = scd::reader::parse(&authentic)
                .unwrap_or_else(|err| panic!("{} as {id:04X}: {err:#}", path.display()))
                .digest();
            let container = compile(&text, variant, path);
            let file = scd_dir.join(format!("{id:04x}.scd"));
            std::fs::write(&file, container).expect("failed to write room bytecode");
            writeln!(
                out,
                "    RoomScript {{ id: 0x{id:04X}, original: 0x{original:016X}, \
                 container: include_bytes!({:?}) }},",
                file.to_string_lossy()
            )
            .expect("writing to a String cannot fail");
        }
    }
    out.push_str("]\n");
    std::fs::write(out_dir.join("room_scripts.rs"), out)
        .expect("failed to write the generated room script table");
}
