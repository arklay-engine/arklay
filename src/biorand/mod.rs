//! BioRand: generate a small playable game pack from a seed and the installed
//! base pack.
//!
//! The pack is an ordinary `kind = "base"` game with just the seed's rooms and
//! enemies. A room's `random.xml` says what may be done with it, [`plan`] picks
//! the route from those files alone, [`emit`] rewrites the chosen rooms' scripts
//! to match, and [`verify`] checks the result from the finished pack.
//!
//! The same seed and [`GENERATOR_VERSION`] always make the same bytes; bump the
//! version whenever a change would alter a seed's output.

mod emit;
mod ids;
pub mod plan;
mod rng;
pub mod rules;
mod verify;

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, anyhow, bail};

use crate::manifest::Manifest;
use crate::pack::{Pack, PackWriter};

/// The version of the generator's output for a given seed.
pub const GENERATOR_VERSION: u32 = 1;

/// The base pack a game is generated from.
pub const BASE_PACK_ID: &str = "re1";

/// The largest seed: seeds are six digits.
pub const MAX_SEED: u32 = 999_999;
/// How many digits a seed can be written with.
pub const SEED_DIGITS: usize = 6;

/// The pack id of a seed's game.
pub fn pack_id(seed: u32) -> String {
    format!("biorand-{seed:06}")
}

/// A seed's game file in the games directory.
pub fn pack_path(games_dir: &Path, seed: u32) -> PathBuf {
    games_dir.join(format!("{}.akpak", pack_id(seed)))
}

/// A seed from the system clock, for the launcher to offer.
pub fn random_seed() -> u32 {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.subsec_nanos());
    nanos.wrapping_mul(2_654_435_761) % (MAX_SEED + 1)
}

/// The room a pack path names the script of: `room/21a/room.scd`.
pub(crate) fn script_room(path: &str) -> Option<u16> {
    let id = path.strip_prefix("room/")?.strip_suffix("/room.scd")?;
    u16::from_str_radix(id, 16).ok()
}

/// The room a door's `next_room` byte names from a room in `stage`.
#[cfg(test)]
pub(crate) fn room_of(next_room: u8, stage: u8) -> u16 {
    ids::room_of(next_room, stage)
}

/// Each room's item slots, from the `random.xml` files of a pack.
#[cfg(test)]
pub(crate) fn slots_in(
    pack: &Pack,
) -> Result<std::collections::BTreeMap<u16, std::collections::BTreeSet<u8>>> {
    let paths: Vec<String> = pack.own_paths().map(str::to_string).collect();
    let pool = read_pool(&paths, &|path| Ok(pack.read(path)?.to_vec()))?;
    Ok(pool
        .into_iter()
        .map(|rules| (rules.room, rules.items.into_iter().collect()))
        .collect())
}

/// The facing that looks from `from` to `to`, for the playthrough bot.
#[cfg(test)]
pub(crate) fn angle_towards(from: [i32; 3], to: [i32; 3]) -> u16 {
    let (dx, dz) = (f64::from(to[0] - from[0]), f64::from(to[2] - from[2]));
    let turns = (-dz).atan2(dx) / std::f64::consts::TAU;
    (turns.rem_euclid(1.0) * 4096.0) as u16 & 0x0FFF
}

/// The rooms with a `random.xml` among `paths`.
fn read_pool(
    paths: &[String],
    read: &dyn Fn(&str) -> Result<Vec<u8>>,
) -> Result<Vec<rules::RoomRules>> {
    let mut pool = Vec::new();
    for path in paths {
        let Some(id) = path
            .strip_prefix("room/")
            .and_then(|rest| rest.strip_suffix("/random.xml"))
        else {
            continue;
        };
        let room = u16::from_str_radix(id, 16).with_context(|| format!("bad room in {path}"))?;
        let text =
            String::from_utf8(read(path)?).with_context(|| format!("{path} is not UTF-8"))?;
        pool.push(rules::parse(room, &text).with_context(|| format!("failed to read {path}"))?);
    }
    Ok(pool)
}

/// The entries that make a seed's game different from its base.
struct Generated {
    manifest: Manifest,
    /// Rewritten scripts by entry, ending up in the pack in this order.
    scripts: std::collections::BTreeMap<String, Vec<u8>>,
    plan: plan::Plan,
}

fn generate_entries(
    seed: u32,
    base: &Manifest,
    paths: &[String],
    read: &dyn Fn(&str) -> Result<Vec<u8>>,
) -> Result<Generated> {
    if seed > MAX_SEED {
        bail!("seed {seed} has more than six digits");
    }
    let pool = read_pool(paths, read)?;
    let plan = plan::plan(seed, &pool).with_context(|| format!("seed {seed} has no game"))?;
    let scripts = emit::room_scripts(&plan, read)?;

    let mut manifest = Manifest::base(pack_id(seed));
    manifest.name = Some(format!("BioRand {seed:06}"));
    manifest.version.clone_from(&base.version);
    manifest.description = Some(format!("Generated by BioRand from {}", base.id));
    manifest.language.clone_from(&base.language);
    manifest.region = base.region;
    manifest.convert_version = base.convert_version;
    manifest.seed = Some(seed);
    manifest.generator_version = Some(GENERATOR_VERSION);
    manifest.character = Some(plan.character);
    manifest.start_room = Some(format!("{:03x}", plan.start));
    manifest.start_pos = Some([
        i32::from(plan.start_entrance.x),
        i32::from(plan.start_entrance.y),
        i32::from(plan.start_entrance.z),
    ]);
    manifest.start_angle = Some(plan.start_entrance.d as u16);
    Ok(Generated {
        manifest,
        scripts,
        plan,
    })
}

/// Whether a base entry goes in the seed's pack as it is. Rooms and enemies are
/// kept per seed; the attract reels play rooms the game may not have.
fn keep_entry(path: &str, plan: &plan::Plan, enemies: &std::collections::BTreeSet<u8>) -> bool {
    if path == "manifest.toml" || path == "game/new_game.lua" || path.starts_with("demo/") {
        return false;
    }
    if let Some(rest) = path.strip_prefix("room/") {
        let id = rest.split('/').next().unwrap_or_default();
        return u16::from_str_radix(id, 16).is_ok_and(|room| plan.rooms.contains_key(&room));
    }
    if let Some(rest) = path.strip_prefix("enemy/") {
        // Every behaviour script stays: one enemy's can require another's.
        let id = rest.split('/').next().unwrap_or_default();
        return path.ends_with(".lua")
            || u8::from_str_radix(id, 16).map_or(true, |enemy| enemies.contains(&enemy));
    }
    true
}

/// Generate the game of `seed` from the pack at `base` as `games_dir`'s
/// `biorand-<seed>.akpak`, unless it is already there from this generator and
/// base. `progress` gets `(done, total)` while the pack is written.
pub fn generate(
    base: &Path,
    seed: u32,
    games_dir: &Path,
    jobs: usize,
    progress: &(dyn Fn(u64, u64) + Sync),
) -> Result<PathBuf> {
    let out = pack_path(games_dir, seed);
    let source = Pack::open(base).with_context(|| format!("failed to open {}", base.display()))?;
    let base_manifest = source
        .manifest()
        .ok_or_else(|| anyhow!("{} has no manifest", base.display()))?;
    if let Ok(Some(existing)) = crate::pack::read_manifest(&out)
        && existing.seed == Some(seed)
        && existing.generator_version == Some(GENERATOR_VERSION)
        && existing.convert_version == base_manifest.convert_version
    {
        return Ok(out);
    }

    let paths: Vec<String> = source.own_paths().map(str::to_string).collect();
    let read = |path: &str| -> Result<Vec<u8>> { Ok(source.read(path)?.to_vec()) };
    let generated = generate_entries(seed, base_manifest, &paths, &read)?;

    let mut enemies = std::collections::BTreeSet::new();
    for scd in generated.scripts.values() {
        enemies.extend(emit::enemies_in(scd)?);
    }
    let mut writer = PackWriter::new();
    let manifest_text = generated.manifest.render();
    writer.add("manifest.toml", manifest_text.into_bytes())?;
    writer.add(
        "game/new_game.lua",
        emit::new_game_lua().as_bytes().to_vec(),
    )?;
    for path in &paths {
        if !keep_entry(path, &generated.plan, &enemies) {
            continue;
        }
        match generated.scripts.get(path) {
            Some(script) => writer.add(path, script.clone())?,
            None => writer.add(path, read(path)?)?,
        }
    }

    let total = writer.len() as u64;
    let done = std::sync::atomic::AtomicU64::new(0);
    writer.compress_entries_reporting(jobs, crate::convert::is_precompressed, |_| {
        let finished = done.fetch_add(1, std::sync::atomic::Ordering::Relaxed) + 1;
        progress(finished, total);
    })?;
    std::fs::create_dir_all(games_dir)
        .with_context(|| format!("failed to create {}", games_dir.display()))?;
    writer
        .write(&out)
        .with_context(|| format!("failed to write {}", out.display()))?;
    if let Err(err) = verify_pack(&out) {
        // Leave nothing the Play list would offer.
        let _ = std::fs::remove_file(&out);
        return Err(err.context(format!("seed {seed} made a broken game")));
    }
    Ok(out)
}

/// Check a generated game from what its pack file holds.
pub fn verify_pack(path: &Path) -> Result<()> {
    let pack = Pack::open(path).with_context(|| format!("failed to open {}", path.display()))?;
    let manifest = pack
        .manifest()
        .ok_or_else(|| anyhow!("{} has no manifest", path.display()))?;
    let paths: Vec<String> = pack.own_paths().map(str::to_string).collect();
    verify::verify_entries(manifest, &paths, &|path| Ok(pack.read(path)?.to_vec()))
}

#[cfg(test)]
pub(crate) fn embedded_read(path: &str) -> Result<Vec<u8>> {
    if let Some(room) = script_room(path) {
        return crate::scd::ROOM_SCRIPTS
            .iter()
            .find(|script| script.room == room)
            .map(|script| script.container.to_vec())
            .ok_or_else(|| anyhow!("no script for {path}"));
    }
    let file = path.strip_prefix("room/").unwrap_or(path);
    crate::room::RE1_FILES
        .iter()
        .find(|(entry, _)| *entry == file)
        .map(|(_, text)| text.as_bytes().to_vec())
        .ok_or_else(|| anyhow!("no embedded {path}"))
}

#[cfg(test)]
pub(crate) fn embedded_paths() -> Vec<String> {
    crate::room::RE1_FILES
        .iter()
        .map(|(entry, _)| format!("room/{entry}"))
        .chain(
            crate::scd::ROOM_SCRIPTS
                .iter()
                .map(|script| format!("room/{:03x}/room.scd", script.room)),
        )
        .collect()
}

#[cfg(test)]
pub(crate) fn embedded_pool() -> Vec<rules::RoomRules> {
    read_pool(&embedded_paths(), &embedded_read).unwrap()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn generate_scripts(seed: u32) -> Generated {
        let base = Manifest::base("re1");
        generate_entries(seed, &base, &embedded_paths(), &embedded_read).unwrap()
    }

    /// The rooms' finished entries, as a pack of them would hold.
    fn verify_generated(generated: &Generated) -> Result<()> {
        let paths: Vec<String> = generated.scripts.keys().cloned().collect();
        verify::verify_entries(&generated.manifest, &paths, &|path| match generated
            .scripts
            .get(path)
        {
            Some(script) => Ok(script.clone()),
            None => embedded_read(path),
        })
    }

    #[test]
    fn a_seed_makes_the_same_scripts_every_time() {
        for seed in [0, 1, 424_242, MAX_SEED] {
            let one = generate_scripts(seed);
            let two = generate_scripts(seed);
            assert_eq!(one.scripts, two.scripts);
            assert_eq!(one.manifest.render(), two.manifest.render());
        }
    }

    #[test]
    fn seeds_differ() {
        assert_ne!(generate_scripts(1).scripts, generate_scripts(2).scripts);
    }

    #[test]
    fn hundreds_of_seeds_verify() {
        for seed in 0..500 {
            let generated = generate_scripts(seed * 2003);
            verify_generated(&generated).unwrap_or_else(|error| {
                panic!("seed {}: {error:#}", seed * 2003);
            });
        }
    }

    #[test]
    fn the_verifier_catches_an_unreachable_key() {
        let mut generated = generate_scripts(7);
        // Swap the flare's room script for the vanilla one: the patched doors
        // no longer lead back, which the verifier must notice.
        let goal = generated
            .plan
            .rooms
            .keys()
            .copied()
            .find(|&room| room != generated.plan.start)
            .unwrap();
        let entry = format!("room/{goal:03x}/room.scd");
        generated
            .scripts
            .insert(entry.clone(), embedded_read(&entry).unwrap());
        assert!(verify_generated(&generated).is_err());
    }

    /// A base pack of the embedded rooms and a little of everything else.
    fn write_base(dir: &Path) -> PathBuf {
        let path = dir.join("re1.akpak");
        let mut manifest = Manifest::base("re1");
        manifest.convert_version = Some(crate::convert::CONVERT_VERSION);
        let mut writer = PackWriter::new();
        writer
            .add("manifest.toml", manifest.render().into_bytes())
            .unwrap();
        for entry in embedded_paths() {
            writer.add(&entry, embedded_read(&entry).unwrap()).unwrap();
        }
        for entry in [
            "enemy/10/enemy_0.emd",
            "enemy/10/enemy.lua",
            "enemy/0c/enemy_0.emd",
        ] {
            writer.add(entry, b"data".to_vec()).unwrap();
        }
        writer
            .add("enemy/0c/enemy.lua", b"-- shared".to_vec())
            .unwrap();
        writer.add("demo/00.dem", b"reel".to_vec()).unwrap();
        writer
            .add("game/new_game.lua", b"-- vanilla".to_vec())
            .unwrap();
        writer.write(&path).unwrap();
        path
    }

    #[test]
    fn a_generated_pack_is_a_game_of_its_own() {
        let dir = std::env::temp_dir().join(format!("biorand-pack-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let base = write_base(&dir);
        let games = dir.join("games");
        let quiet = |_: u64, _: u64| {};

        let first = generate(&base, 42, &games, 1, &quiet).unwrap();
        assert_eq!(first, games.join("biorand-000042.akpak"));
        let bytes = std::fs::read(&first).unwrap();

        // The same seed and generator: the pack on disk stands.
        let stamp = std::fs::metadata(&first).unwrap().modified().unwrap();
        generate(&base, 42, &games, 1, &quiet).unwrap();
        assert_eq!(
            std::fs::metadata(&first).unwrap().modified().unwrap(),
            stamp
        );

        // Built again from nothing, it is the same to the byte.
        std::fs::remove_file(&first).unwrap();
        generate(&base, 42, &games, 1, &quiet).unwrap();
        assert_eq!(std::fs::read(&first).unwrap(), bytes);

        let pack = Pack::open(&first).unwrap();
        let manifest = pack.manifest().unwrap();
        assert_eq!(manifest.id, "biorand-000042");
        assert_eq!(manifest.seed, Some(42));
        assert_eq!(manifest.generator_version, Some(GENERATOR_VERSION));
        let paths: Vec<&str> = pack.own_paths().collect();
        assert!(
            paths.contains(&"enemy/10/enemy_0.emd"),
            "the finale's enemy"
        );
        assert!(
            paths.contains(&"enemy/0c/enemy.lua"),
            "a script another one requires"
        );
        assert!(
            !paths.contains(&"enemy/0c/enemy_0.emd"),
            "a model nothing places"
        );
        assert!(!paths.iter().any(|path| path.starts_with("demo/")));
        assert_eq!(
            &*pack.read("game/new_game.lua").unwrap(),
            emit::new_game_lua().as_bytes()
        );
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn rejects_a_seed_over_six_digits() {
        let base = Manifest::base("re1");
        assert!(generate_entries(1_000_000, &base, &embedded_paths(), &embedded_read).is_err());
    }
}
