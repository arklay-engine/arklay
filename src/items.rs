pub const MAX_ITEM: u8 = 0x6E;
/// Item id of the Ingram.
pub const ITEM_INGRAM: u8 = 0x6F;
/// Item id of the Minimi.
pub const ITEM_MINIMI: u8 = 0x70;

/// Ink-ribbon item id; a pickup always takes three.
pub const ITEM_INK_RIBBONS: u8 = 0x2F;
/// Merge cap: a merging stack never exceeds this.
pub const ITEM_QUANTITY_CAP: u8 = 0xFA;

/// Icon dimensions of the `ITEM_ALL`/`ITEM_MIX`/`MEDAL` rows.
pub const ICON_WIDTH: u32 = 40;
/// Icon height in pixels.
pub const ICON_HEIGHT: u32 = 30;
/// Bytes in one icon row of the 8bpp sheets.
pub const ICON_ROW_BYTES: usize = (ICON_WIDTH * ICON_HEIGHT) as usize;

/// Number of `ITEM_ALL.PIX` rows.
pub const ITEM_ALL_ROWS: usize = 72;
/// Number of `ITEM_MIX.PIX` rows.
pub const ITEM_MIX_ROWS: usize = 18;
/// Number of `MEDAL.PIX` rows.
pub const MEDAL_ROWS: usize = 2;

/// Pack entry of the `ITEM_ALL` atlas.
pub const ITEM_ALL_ENTRY: &str = "item/item_all.bmp";
/// Pack entry of the `ITEM_MIX` atlas.
pub const ITEM_MIX_ENTRY: &str = "item/item_mix.bmp";
/// Pack entry of the medal atlas.
pub const MEDAL_ENTRY: &str = "item/medal.bmp";

/// One item lookup record.
///
/// `max_quantity` is the byte in front of the icon class, the class is a
/// one-based row/name index, `combine_index` selects the recipe table
/// (`0x80` = not combinable) and `name_class` is `0x80` for an item with a
/// real name or a small index into the generic-name table otherwise.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct ItemRecord {
    /// Stack maximum (0 for items whose quantity is not shown).
    pub max_quantity: u8,
    /// One-based icon class / model-name index.
    pub image_class: u8,
    /// Combine-table index, or `0x80` when the item cannot be combined.
    pub combine_index: u8,
    /// `0x80` for a real name, else the generic-name class.
    pub name_class: u8,
}

impl ItemRecord {
    /// Whether the item has its own name.
    pub fn name_valid(&self) -> bool {
        self.name_class == 0x80
    }

    /// The `ITEM_MIX.PIX` sprite row this item's combine index maps to, if
    /// any. Most items draw from `ITEM_ALL` instead, so this is usually
    /// `None`.
    pub fn mix_row(&self) -> Option<u8> {
        mix_row(self.combine_index)
    }
}

/// The lookup record for `item`, or `None` for id 0, out-of-range ids and the
/// two PC-only machineguns.
pub fn record(item: u8) -> Option<ItemRecord> {
    if item == 0 || item > MAX_ITEM {
        return None;
    }
    let base = usize::from(item) * 4;
    Some(ItemRecord {
        max_quantity: ITEM_LOOKUP.get(base - 1).copied().unwrap_or(0),
        image_class: ITEM_LOOKUP[base],
        combine_index: ITEM_LOOKUP[base + 1],
        name_class: ITEM_LOOKUP[base + 2],
    })
}

/// The item id of the red book (the item viewer's zoom special case).
pub const ITEM_RED_BOOK: u8 = 0x3E;
/// The item id of the first-aid spray (the zoom path's upper bound).
pub const ITEM_FIRST_AID_SPRAY: u8 = 0x41;
/// The item id of the green herb (`G`).
pub const ITEM_GREEN_HERB: u8 = 0x44;
/// The item id of the blue herb, the poison cure.
pub const ITEM_BLUE_HERB: u8 = 0x45;
/// The item id of the green and red herb mix (`GR`).
pub const ITEM_GREEN_RED_HERB: u8 = 0x46;
/// The item id of the two green herbs mix (`GG`).
pub const ITEM_GREEN_GREEN_HERB: u8 = 0x47;
/// The item id of the green and blue herb mix (`GB`).
pub const ITEM_GREEN_BLUE_HERB: u8 = 0x48;
/// The item id of the green, red and blue herb mix (`GRB`).
pub const ITEM_GREEN_RED_BLUE_HERB: u8 = 0x49;
/// The item id of the three green herbs mix (`GGG`).
pub const ITEM_GREEN_GREEN_GREEN_HERB: u8 = 0x4A;
/// The item id of the two green herbs and blue herb mix (`GGB`).
pub const ITEM_GREEN_GREEN_BLUE_HERB: u8 = 0x4B;

/// Offset of the item-examine combo table inside [`ITEM_LOOKUP`].
pub const EXAMINE_COMBOS_OFFSET: usize = 0x16B;
/// Offset of the item-examine type table inside [`ITEM_LOOKUP`].
const EXAMINE_TYPES_OFFSET: usize = 0x19B;
/// Number of 12-byte examine-combo records.
pub const EXAMINE_COMBO_COUNT: usize = 4;

/// The examine-type byte for an item flag index: the high nibble is the number
/// of combo records to try from the low nibble's record index. `None` past the
/// 48-entry table (no shipped item reaches one).
pub fn examine_type(flag_index: u8) -> Option<u8> {
    ITEM_LOOKUP
        .get(EXAMINE_TYPES_OFFSET + usize::from(flag_index))
        .copied()
}

/// The `index`th examine-combo record: the model's pitch/yaw/roll
/// `(target, tolerance)` windows in 12-bit GTE angle units, or `None` past the
/// four records.
pub fn examine_combo(index: usize) -> Option<[(u16, u16); 3]> {
    if index >= EXAMINE_COMBO_COUNT {
        return None;
    }
    let base = EXAMINE_COMBOS_OFFSET.checked_add(index.checked_mul(12)?)?;
    let bytes = ITEM_LOOKUP.get(base..base + 12)?;
    let word = |word: usize| u16::from_le_bytes([bytes[word * 2], bytes[word * 2 + 1]]);
    Some([(word(0), word(1)), (word(2), word(3)), (word(4), word(5))])
}

/// The icon class of `item` (0 when unknown).
pub fn image_class(item: u8) -> u8 {
    record(item).map_or(0, |record| record.image_class)
}

/// The combine-table index of `item`, or `0x80` when unknown/not combinable.
pub fn combine_index(item: u8) -> u8 {
    record(item).map_or(0x80, |record| record.combine_index)
}

/// The `ITEM_MIX.PIX` row for a combine index (`1`-based), or `None`.
pub fn mix_row(combine_index: u8) -> Option<u8> {
    if combine_index == 0x80 {
        return None;
    }
    let row = *ITEM_IMAGE_ROW.get(usize::from(combine_index))?;
    (row != 0).then_some(row)
}

/// One combine recipe record.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CombineRecord {
    /// The other item to mix with.
    pub other_item: u8,
    /// Item the cursor slot becomes.
    pub new_cursor: u8,
    /// Item the target slot becomes (0 = the slot is emptied).
    pub new_target: u8,
    /// Effect id (0 none, 1/2 ammo transfer, 3 quantity merge, 4 chemical
    /// flag, 5 mode, 6/7 ammo transfer with an empty/loaded check).
    pub effect: u8,
}

/// One combine table: a count byte followed by [`CombineRecord`]s.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CombineTable {
    data: &'static [u8],
    count: usize,
}

impl CombineTable {
    /// Number of records.
    pub fn len(&self) -> usize {
        self.count
    }

    /// Whether the table has no records.
    pub fn is_empty(&self) -> bool {
        self.count == 0
    }

    /// Iterate the records in table order.
    pub fn iter(&self) -> impl Iterator<Item = CombineRecord> + '_ {
        self.data
            .as_chunks::<4>()
            .0
            .iter()
            .take(self.count)
            .map(|record| CombineRecord {
                other_item: record[0],
                new_cursor: record[1],
                new_target: record[2],
                effect: record[3],
            })
    }

    /// The first recipe whose other item is `other`.
    pub fn find(&self, other: u8) -> Option<CombineRecord> {
        self.iter().find(|record| record.other_item == other)
    }
}

/// The combine table at `index` (the lookup record's combine byte). An
/// out-of-range or "not combinable" index yields an empty table.
pub fn combine_table(index: u8) -> CombineTable {
    let Some(&offset) = COMBINE_OFFSETS.get(usize::from(index)) else {
        return CombineTable {
            data: &[],
            count: 0,
        };
    };
    let offset = usize::from(offset);
    let count = usize::from(COMBINE_DATA.get(offset).copied().unwrap_or(0));
    let data = COMBINE_DATA.get(offset + 1..).unwrap_or(&[]);
    CombineTable { data, count }
}

/// The recipe for mixing `item` into `other`, or `None` when they do not mix.
pub fn combine(item: u8, other: u8) -> Option<CombineRecord> {
    let index = combine_index(item);
    if index == 0x80 {
        return None;
    }
    combine_table(index).find(other)
}

/// The item-view file name for an icon class (`0..=0x4A`).
pub fn model_name_for_class(image_class: u8) -> Option<&'static str> {
    let name = MODEL_NAMES.get(usize::from(image_class))?;
    let end = name
        .iter()
        .position(|&byte| byte == 0)
        .unwrap_or(name.len());
    std::str::from_utf8(&name[..end]).ok()
}

/// The `ITEM_ALL` row (zero-based) of `item`'s 40x30 icon, or `None` when the
/// item has no icon there.
pub fn icon_row(item: u8) -> Option<u8> {
    let class = image_class(item);
    let row = class.checked_sub(1)?;
    (usize::from(row) < ITEM_ALL_ROWS).then_some(row)
}

/// The item-view file name for `item`, including the two PC-only machineguns.
///
/// An item whose image class is 0 has no art: it must not resolve to the
/// placeholder `m` entry.
pub fn model_name(item: u8) -> Option<&'static str> {
    match item {
        ITEM_INGRAM => Some("ING"),
        ITEM_MINIMI => Some("MINI"),
        _ => {
            let class = image_class(item);
            (class != 0).then(|| model_name_for_class(class)).flatten()
        }
    }
}

/// Every item id that has a per-item icon or model, in id order.
///
/// The two PC-only machineguns are included; they are past [`MAX_ITEM`] but
/// still have art.
pub fn art_items() -> impl Iterator<Item = u8> {
    (1..=MAX_ITEM)
        .filter(|&item| icon_row(item).is_some() || model_name(item).is_some())
        .chain([ITEM_INGRAM, ITEM_MINIMI])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_tail_views_overlap_the_lookup_exactly() {
        assert_eq!(
            HEAL_TABLE.as_slice(),
            &ITEM_LOOKUP[HEAL_OFFSET..HEAL_OFFSET + HEAL_TABLE.len()]
        );
    }

    #[test]
    fn examine_tables_are_indexed_from_the_lookup() {
        // Types: 0x10 -> one record from 0, 0x11 -> one from 1, 0x21 -> two
        // from 1, 0x13 -> one from 3.
        assert_eq!(examine_type(0), Some(0x10));
        assert_eq!(examine_type(3), Some(0x11));
        assert_eq!(examine_type(11), Some(0x21));
        assert_eq!(examine_type(13), Some(0x13));
        assert_eq!(examine_combo(0), Some([(0, 0), (300, 3072), (0, 0)]));
        assert_eq!(examine_combo(1), Some([(0, 0), (560, 0), (560, 2048)]));
        assert_eq!(examine_combo(2), Some([(0, 0), (560, 0), (560, 0)]));
        assert_eq!(examine_combo(3), Some([(0, 0), (400, 1024), (0, 0)]));
        assert_eq!(examine_combo(4), None);
    }

    #[test]
    fn lookup_records_are_rotated_with_the_max_in_front() {
        assert_eq!(record(0), None);
        assert_eq!(record(MAX_ITEM + 1), None);
        assert_eq!(record(ITEM_INGRAM), None);

        // Knife: class 1 (i05v), not combinable, real name, no stack.
        assert_eq!(
            record(1),
            Some(ItemRecord {
                max_quantity: 0,
                image_class: 1,
                combine_index: 0x80,
                name_class: 0x80,
            })
        );
        // Beretta: 15-round clip, class 2, combine table 0.
        assert_eq!(
            record(2),
            Some(ItemRecord {
                max_quantity: 0x0F,
                image_class: 0x02,
                combine_index: 0x00,
                name_class: 0x80,
            })
        );
        // Ink ribbon: max 3, class 0x2C, combine table 0x19.
        assert_eq!(
            record(0x2F),
            Some(ItemRecord {
                max_quantity: 3,
                image_class: 0x2C,
                combine_index: 0x19,
                name_class: 0x80,
            })
        );
        // Green herb: class 0x41, mix table 0x1B, stack max 1.
        assert_eq!(
            record(0x44),
            Some(ItemRecord {
                max_quantity: 1,
                image_class: 0x41,
                combine_index: 0x1B,
                name_class: 0x80,
            })
        );
        assert_eq!(image_class(0x41), 0x3E);
        assert!(record(1).unwrap().name_valid());
    }

    #[test]
    fn known_combine_recipes() {
        // Beretta + clip reloads the gun.
        assert_eq!(
            combine(2, 0x0B),
            Some(CombineRecord {
                other_item: 0x0B,
                new_cursor: 0x02,
                new_target: 0x0B,
                effect: 1,
            })
        );
        // Green herb + red herb -> mixed green+red in the cursor slot.
        assert_eq!(
            combine(0x44, 0x43),
            Some(CombineRecord {
                other_item: 0x43,
                new_cursor: 0x46,
                new_target: 0x00,
                effect: 0,
            })
        );
        // Red herb + green herb -> mixed.
        assert_eq!(
            combine(0x43, 0x44).map(|record| (record.new_cursor, record.effect)),
            Some((0x46, 0))
        );
        // The spray has no combine table.
        assert_eq!(combine(0x41, 0x44), None);
        assert!(combine_table(0x80).is_empty());
        assert!(combine_table(200).is_empty());
    }

    #[test]
    fn combine_tables_are_count_prefixed_and_bounded() {
        let table = combine_table(0);
        assert_eq!(table.len(), 1);
        assert_eq!(table.iter().count(), 1);
        let table = combine_table(0x1B);
        assert_eq!(table.len(), 5);
        assert_eq!(table.iter().count(), 5);
        // The last table runs to the end of the data without overrunning it.
        let last = combine_table(COMBINE_OFFSETS.len() as u8 - 1);
        assert_eq!(last.iter().count(), last.len());
    }

    #[test]
    fn mix_rows_come_from_the_image_row_table() {
        assert_eq!(mix_row(0x00), None);
        assert_eq!(mix_row(0x80), None);
        assert_eq!(mix_row(0x1A), None);
        assert_eq!(mix_row(0x1B), None);
        assert_eq!(mix_row(0x1D), Some(0x0D));
        assert_eq!(mix_row(0x20), Some(0x10));
        assert_eq!(mix_row(0x21), Some(0x11));
        assert_eq!(mix_row(0x22), Some(0x12));
        assert_eq!(record(0x49).unwrap().mix_row(), Some(0x10));
    }

    #[test]
    fn model_names_resolve_for_items_and_classes() {
        assert_eq!(model_name_for_class(1), Some("i05v"));
        assert_eq!(model_name_for_class(2), Some("i00v"));
        assert_eq!(model_name_for_class(0x40), Some("i66v"));
        assert_eq!(model_name_for_class(75), None);
        assert_eq!(model_name(1), Some("i05v"));
        assert_eq!(model_name(2), Some("i00v"));
        assert_eq!(model_name(ITEM_INGRAM), Some("ING"));
        assert_eq!(model_name(ITEM_MINIMI), Some("MINI"));
        assert_eq!(model_name(0), None);
        // A class-0 record must not resolve the placeholder "m" name.
        assert_eq!(model_name(0x6E), None);
        assert_eq!(model_name_for_class(0), Some("m"));
    }

    #[test]
    fn icon_rows_are_zero_based_and_bounded_by_the_atlas() {
        assert_eq!(icon_row(0), None);
        assert_eq!(icon_row(1), Some(0));
        assert_eq!(icon_row(2), Some(1));
        // Classes 73 and 74 have models but no ITEM_ALL row (the sheet is 72
        // rows).
        assert_eq!(image_class(0x4C), 73);
        assert_eq!(icon_row(0x4C), None);
        assert_eq!(icon_row(0x4D), None);
        // Class 0 and the two PC-only ids have no atlas row.
        assert_eq!(icon_row(0x6E), None);
        assert_eq!(icon_row(ITEM_INGRAM), None);
        assert_eq!(icon_row(ITEM_MINIMI), None);
        assert_eq!(icon_row(0x57), None);
    }

    #[test]
    fn art_items_cover_the_shared_classes_and_the_pc_only_ids() {
        let ids: Vec<u8> = art_items().collect();
        assert!(ids.contains(&0x01));
        assert!(ids.contains(&0x4C), "a model-only item is still art");
        assert!(ids.contains(&ITEM_INGRAM));
        assert!(ids.contains(&ITEM_MINIMI));
        assert!(!ids.contains(&0x6E), "no class means no art");
        assert!(!ids.contains(&0x57), "an invalid class has no art");
        assert_eq!(
            ids.len(),
            94,
            "92 item ids with a class plus the two PC-only ids"
        );
        assert!(ids.windows(2).all(|pair| pair[0] < pair[1]), "{ids:?}");
    }
}
