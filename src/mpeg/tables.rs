//! The MPEG-1 video VLC trees, scan and quantiser tables and the MPEG-1
//! audio synthesis window, transcribed mechanically from pl_mpeg
//! (Dominic Szablewski, MIT; <https://github.com/phoboslab/pl_mpeg>), which
//! takes them from ISO/IEC 11172-2 Annex B and 11172-3 Annex B.
//!
//! A VLC tree is a flat array of `(next, value)` pairs, two per node: the bit
//! read selects the pair member, `next > 0` is the offset of the child node,
//! `next == 0` a leaf carrying `value` and `next == -1` an invalid code.

/// One tree entry: `(next node offset, leaf value)`.
pub(super) type Vlc = (i16, i32);

/// The DCT coefficient tree's escape leaf (6-bit run, 8- or 16-bit level).
